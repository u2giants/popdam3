#!/usr/bin/env node
// #469 Tesseract worker termination (finally) — code-path + failure simulation.
// Pins the fix at every audited site and EXECUTES the verbatim fix statement
// against a mock worker whose recognize() rejects, proving terminate() still
// runs (the pre-#713 statement order leaked the worker on failure).
// No production access.

import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { tmpdir } from "node:os";

const root = join(import.meta.dirname, "..", "..");
const sites = [
  "apps/bridge-agent/src/pdf-backfill.ts",
  "apps/bridge-agent/src/pdf-text-sampler.ts",
  "apps/windows-agent/src/pdf-backfill.ts",
  "apps/windows-agent/src/pdf-text-sampler.ts",
];

const fixRe = /const \w+ = await worker\.recognize\(pngBuffer\)\.finally\(\(\) => worker\.terminate\(\)\);/g;
const statements = [];
const pinResults = [];
for (const rel of sites) {
  const src = readFileSync(join(root, rel), "utf8");
  const matches = src.match(fixRe) ?? [];
  const oldLeak = /await worker\.recognize\(pngBuffer\);\s*\n\s*await worker\.terminate\(\);/.test(src);
  pinResults.push({ site: rel, fix_statements: matches.length, old_leak_pattern_remaining: oldLeak });
  for (const m of matches) statements.push({ site: rel, statement: m });
}
console.log(JSON.stringify({ source_pins: pinResults }));
if (pinResults.some((r) => r.fix_statements !== 1 || r.old_leak_pattern_remaining)) {
  console.log(JSON.stringify({ result: "FAIL", reason: "fix statement missing or old leak pattern present" }));
  process.exit(1);
}
console.log(JSON.stringify({ verbatim_statements: statements }));

const generated = `// GENERATED by tesseract-finally-sim.mjs — do not edit.
type Any = any;
const observations: Any[] = [];

function makeWorker(mode: "resolve" | "reject") {
  const state = { terminateCalls: 0, recognizeCalls: 0 };
  const worker = {
    recognize: (_buf: Any) => {
      state.recognizeCalls++;
      return mode === "resolve"
        ? Promise.resolve({ data: { text: "spec sheet text" } })
        : Promise.reject(new Error("simulated OCR recognize failure"));
    },
    terminate: () => { state.terminateCalls++; return Promise.resolve(); },
  };
  return { worker, state };
}

${statements
  .map((s, i) => {
    const n = i + 1;
    return `
// ==== VERBATIM FIX STATEMENT from ${s.site} ====
const fixStmt_${n} = ${JSON.stringify(s.statement)};
// success path
{
  const { worker, state } = makeWorker("resolve");
  const pngBuffer = Buffer.alloc(1);
  let result: Any = null;
  let threw: Any = null;
  const body = fixStmt_${n}.replace(/^const \\w+ = /, "result = ");
  try { await eval("(async()=>{" + body + "})()"); } catch (e) { threw = e; }
  observations.push({ site: ${JSON.stringify(s.site)}, case: "recognize_resolves", terminate_calls: state.terminateCalls, threw: threw && threw.message, text: result && result.data.text, pass: state.terminateCalls === 1 && !threw });
}
// failure path — the audit case: recognize rejects, terminate must still run
{
  const { worker, state } = makeWorker("reject");
  const pngBuffer = Buffer.alloc(1);
  let result: Any = null;
  let threw: Any = null;
  const body = fixStmt_${n}.replace(/^const \\w+ = /, "result = ");
  try { await eval("(async()=>{" + body + "})()"); } catch (e) { threw = e; }
  observations.push({ site: ${JSON.stringify(s.site)}, case: "recognize_rejects", terminate_calls: state.terminateCalls, threw: threw && threw.message, pass: state.terminateCalls === 1 && !!threw });
}
// control: pre-#713 statement order leaks the worker when recognize rejects
{
  const { worker, state } = makeWorker("reject");
  const pngBuffer = Buffer.alloc(1);
  let threw: Any = null;
  try {
    await eval("(async()=>{const result = await worker.recognize(pngBuffer); await worker.terminate();})()");
  } catch (e) { threw = e; }
  observations.push({ site: ${JSON.stringify(s.site)}, case: "pre_713_leak_control", terminate_calls: state.terminateCalls, threw: threw && threw.message, pass: state.terminateCalls === 0 && !!threw });
}
`;
  })
  .join("\n")}

console.log(JSON.stringify({ observations }, null, 2));
const ok = observations.length === ${statements.length * 3} && observations.every((o) => o.pass === true);
console.log(JSON.stringify({ result: ok ? "PASS" : "FAIL" }));
if (!ok) process.exit(1);
`;

const outFile = join(tmpdir(), "tesseract-finally-sim.generated.ts");
writeFileSync(outFile, generated, "utf8");
console.log(JSON.stringify({ generated_file: outFile }));
const run = spawnSync(process.execPath, [outFile], { encoding: "utf8" });
process.stdout.write(run.stdout);
process.stderr.write(run.stderr);
process.exit(run.status ?? 1);
