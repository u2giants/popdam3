#!/usr/bin/env node
// #469 batch loop cap (MAX_BATCH_LOOPS = 10_000) simulation.
// Extracts the REAL capped loop bodies verbatim from the three component files
// named in the audit (four loops: PopSGSettingsPage x2, ScanAndOutputSettings,
// ActionsSection), runs each against a never-completing mock batch call, and
// asserts the cap fires at exactly 10,000 iterations with the exact error text.
// A completion control per loop proves the cap does not fire early.
// No production access; no production data touched.

import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { tmpdir } from "node:os";

const root = join(import.meta.dirname, "..", "..");
const files = {
  popsg: join(root, "src", "pages", "popsg", "PopSGSettingsPage.tsx"),
  scan: join(root, "src", "components", "settings", "worker-management", "ScanAndOutputSettings.tsx"),
  actions: join(root, "src", "components", "settings", "diagnostics", "ActionsSection.tsx"),
};

// --- source pins ---
const capLine = 'if (batch >= MAX_BATCH_LOOPS) throw new Error("Stopped after too many batches; run it again to continue.");';
const pinResults = [];
let capDeclLine = null;
for (const [name, path] of Object.entries(files)) {
  const src = readFileSync(path, "utf8");
  const decl = "const MAX_BATCH_LOOPS = 10_000;";
  const loops = src.split(capLine).length - 1;
  const declLine = src.split("\n").find((l) => l.trimEnd().endsWith("const MAX_BATCH_LOOPS = 10_000;")) ?? null;
  if (declLine && !capDeclLine) capDeclLine = declLine.trimEnd();
  pinResults.push({ file: name, cap_declared: src.includes(decl), cap_check_count: loops, decl_line: declLine });
}
console.log(JSON.stringify({ source_pins: pinResults }));
if (pinResults.some((r) => !r.cap_declared || r.cap_check_count < 1)) {
  console.log(JSON.stringify({ result: "FAIL", reason: "source pin missing" }));
  process.exit(1);
}

// Extract each `for (let batch = 0; ; batch++) { ... }` block verbatim (brace-balanced).
function extractLoops(src) {
  const out = [];
  const re = /for \(let batch = 0; ; batch\+\+\) \{/g;
  let m;
  while ((m = re.exec(src))) {
    let depth = 1;
    let i = m.index + m[0].length;
    while (depth > 0 && i < src.length) {
      if (src[i] === "{") depth++;
      else if (src[i] === "}") depth--;
      i++;
    }
    out.push(src.slice(m.index, i));
  }
  return out;
}

const loops = [];
for (const [name, path] of Object.entries(files)) {
  const found = extractLoops(readFileSync(path, "utf8"));
  found.forEach((body, idx) => loops.push({ name: `${name}#${idx + 1}`, body }));
}
console.log(JSON.stringify({ extracted_loops: loops.map((l) => ({ name: l.name, bytes: l.body.length })) }));

const loopDefs = loops
  .map(
    (l, i) => `
// ==== VERBATIM LOOP EXTRACT ${l.name} ====
async function loop_${i + 1}(supabase: Any, call: Any, thumbVal: string): Promise<Any> {
  let total = 0;
  let totalPurged = 0;
  let totalGroupsRemoved = 0;
  let totalGroupsUpdated = 0;
  ${l.body}
  return { total, totalPurged, totalGroupsRemoved, totalGroupsUpdated };
}
`
  )
  .join("\n");

const driver = loops
  .map((l, i) => {
    const n = i + 1;
    return `
// --- run ${l.name} ---
{
  const never = makeNeverDone(${JSON.stringify(l.name)});
  let caught: Any = null;
  try { await loop_${n}(never.supabase, never.call, "2020-01-01"); } catch (e) { caught = e; }
  const okCap = caught && caught.message === EXPECT_MSG && never.state.calls === 10_000;
  results.push({ loop: ${JSON.stringify(l.name)}, case: "never_done", calls: never.state.calls, error: caught && caught.message, pass: okCap });

  const done3 = makeCompletesAt3(${JSON.stringify(l.name)});
  let caught2: Any = null;
  try { await loop_${n}(done3.supabase, done3.call, "2020-01-01"); } catch (e) { caught2 = e; }
  const okCtl = !caught2 && done3.state.calls === 3;
  results.push({ loop: ${JSON.stringify(l.name)}, case: "completes_at_3", calls: done3.state.calls, error: caught2 && caught2.message, pass: okCtl });
}`;
  })
  .join("\n");

const final = `// GENERATED by batch-loop-cap-sim.mjs — do not edit.
type Any = any;
const results: Any[] = [];
const EXPECT_MSG = "Stopped after too many batches; run it again to continue.";
// verbatim from component source (pinned above):
${capDeclLine}

function makeNeverDone(name: string) {
  const state = { calls: 0 };
  const supabase = {
    rpc: async (_fn: string, _args?: Any) => { state.calls++; return { data: 500, error: null }; },
  };
  const call = async (_action: string, _body?: Any) => {
    state.calls++;
    return { done: false, assets_purged: 10, groups_removed: 0, groups_updated: 0 };
  };
  return { name, state, supabase, call };
}
function makeCompletesAt3(name: string) {
  const state = { calls: 0 };
  const supabase = {
    rpc: async (_fn: string, _args?: Any) => {
      state.calls++;
      return { data: state.calls >= 3 ? 0 : 500, error: null };
    },
  };
  const call = async (_action: string, _body?: Any) => {
    state.calls++;
    return { done: state.calls >= 3, assets_purged: 10, groups_removed: 0, groups_updated: 0 };
  };
  return { name, state, supabase, call };
}
${loopDefs}
${driver}

console.log(JSON.stringify({ observations: results }, null, 2));
const ok = results.length === ${loops.length * 2} && results.every((r) => r.pass === true);
console.log(JSON.stringify({ result: ok ? "PASS" : "FAIL" }));
if (!ok) process.exit(1);
`;

const outFile = join(tmpdir(), "batch-loop-cap-sim.generated.ts");
writeFileSync(outFile, final, "utf8");
console.log(JSON.stringify({ generated_file: outFile }));
const run = spawnSync(process.execPath, [outFile], { encoding: "utf8" });
process.stdout.write(run.stdout);
process.stderr.write(run.stderr);
process.exit(run.status ?? 1);
