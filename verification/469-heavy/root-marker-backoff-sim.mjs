#!/usr/bin/env node
// #469 ensureRootMarkers hourly-backoff simulation.
// Extracts the REAL ensureRootMarkers + backoff constants verbatim from
// apps/bridge-agent/src/index.ts (the deployed source), wires controlled stubs
// for fs / docker-fallback / clock, and drives the read-only-share failure
// sequence. Prints one JSON line per observation. No production access.

import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { tmpdir } from "node:os";

const INDEX = join(import.meta.dirname, "..", "..", "apps", "bridge-agent", "src", "index.ts");
const src = readFileSync(INDEX, "utf8");
const lines = src.split("\n");

// --- source pin: the deployed fix must be present verbatim ---
const pins = [
  "const MARKER_DOCKER_RETRY_MS = 60 * 60 * 1000;",
  'error: "docker_write_backoff"',
  "markerDockerRetryAfter.set(rm.root_id, Date.now() + MARKER_DOCKER_RETRY_MS)",
  "markerDockerRetryAfter.delete(rm.root_id)",
];
const pinResults = pins.map((p) => ({ pin: p, present: src.includes(p) }));
console.log(JSON.stringify({ source_pins: pinResults }));
if (pinResults.some((r) => !r.present)) {
  console.log(JSON.stringify({ result: "FAIL", reason: "source pin missing" }));
  process.exit(1);
}

// Slice: comment + MARKER_DOCKER_RETRY_MS + markerDockerRetryAfter + ensureRootMarkers
// (lines 513..619 1-based). Boundaries located by the function names below.
const startIdx = lines.findIndex((l) => l.includes("// A read-only root fails every heartbeat"));
const endIdx = lines.findIndex((l, i) => i > startIdx && l.trimEnd() === "function applyCloudConfig(cfg: CloudConfig) {");
if (startIdx < 0 || endIdx < 0) {
  console.log(JSON.stringify({ result: "FAIL", reason: "slice boundaries not found" }));
  process.exit(1);
}
const slice = lines.slice(startIdx, endIdx).join("\n").trimEnd();
console.log(JSON.stringify({ extracted: { from_line: startIdx + 1, to_line: endIdx, bytes: slice.length } }));

const generated = `// GENERATED by root-marker-backoff-sim.mjs — do not edit.
// Stubs below stand in for index.ts module scope; the extracted block in the
// middle is verbatim source from apps/bridge-agent/src/index.ts.

type Any = any;
const observations: Any[] = [];
function obs(o: Any) { observations.push(o); }

// ---- clock stub (the backoff gate reads Date.now) ----
let now = 1_800_000_000_000;
(Date as Any).now = () => now;

// ---- fs stubs ----
const dirSet = new Set<string>(["/data", "/data/Decor", "/data/Decor2"]);
const files = new Map<string, string>();
let directWriteFails = true;
async function stat(p: string): Promise<Any> {
  if (!dirSet.has(p)) { const e: Any = new Error("ENOENT"); e.code = "ENOENT"; throw e; }
  return { isDirectory: () => true };
}
async function readFile(p: string, _enc: string): Promise<string> {
  const v = files.get(p);
  if (v === undefined) { const e: Any = new Error("ENOENT"); e.code = "ENOENT"; throw e; }
  return v;
}
async function writeFile(p: string, content: string, _enc: string): Promise<void> {
  if (directWriteFails) { const e: Any = new Error("EROFS"); e.code = "EROFS"; throw e; }
  files.set(p, content);
}

// ---- docker-fallback stub (writeMarkerViaDocker) ----
let dockerCalls = 0;
let dockerFails = true;
let lastDockerArgs: Any = null;
async function writeMarkerViaDocker(containerPath: string, containerMountRoot: string, nasHostPath: string, marker: Any): Promise<void> {
  dockerCalls++;
  lastDockerArgs = { containerPath, containerMountRoot, nasHostPath, marker };
  if (dockerFails) throw new Error("simulated docker write failure (read-only share)");
}

// ---- module scope of index.ts ----
const logs: Any[] = [];
const logger = {
  info: (m: string, meta?: Any) => logs.push(["info", m, meta]),
  warn: (m: string, meta?: Any) => logs.push(["warn", m, meta]),
  error: (m: string, meta?: Any) => logs.push(["error", m, meta]),
};
const markerStatuses: Any = {};
const config = { nasContainerMountRoot: "/data" };
let cloudMountRoot = "";
let cloudNasHostPath = "/volume1/nas";

// ==== BEGIN VERBATIM EXTRACT (apps/bridge-agent/src/index.ts) ====
${slice}
// ==== END VERBATIM EXTRACT ====

const roots = [{ root_id: "Decor", display_name: "Decor", server_path: "Decor" }];

// A: read-only share — direct write fails (EROFS), docker fallback also fails.
await ensureRootMarkers(roots);
obs({
  scenario: "A_first_failure",
  docker_calls: dockerCalls,
  status: markerStatuses["Decor"],
  backoff_set: markerDockerRetryAfter.get("Decor") === now + MARKER_DOCKER_RETRY_MS,
  retry_ms_constant: MARKER_DOCKER_RETRY_MS,
});

// B: next heartbeat 60 s later — must NOT spawn docker again (old code did, every 30 s).
now += 60_000;
await ensureRootMarkers(roots);
obs({
  scenario: "B_within_backoff_window",
  docker_calls: dockerCalls,
  status: markerStatuses["Decor"],
  gate_skipped_docker: dockerCalls === 1,
});

// C: heartbeat still inside the hour — still gated.
now += 30 * 60_000;
await ensureRootMarkers(roots);
obs({
  scenario: "C_still_within_hour",
  docker_calls: dockerCalls,
  status: markerStatuses["Decor"],
});

// D: past the one-hour backoff — exactly one docker retry is allowed.
now += 31 * 60_000; // total > 1 h since failure
await ensureRootMarkers(roots);
obs({
  scenario: "D_after_one_hour",
  docker_calls: dockerCalls,
  retried_once: dockerCalls === 2,
  backoff_still_set: markerDockerRetryAfter.has("Decor"),
});

// E: docker write now succeeds — backoff cleared, status ok.
dockerFails = false;
now += 60 * 60_000 + 60_000;
await ensureRootMarkers(roots);
obs({
  scenario: "E_docker_success_clears_backoff",
  docker_calls: dockerCalls,
  status: markerStatuses["Decor"],
  backoff_cleared: !markerDockerRetryAfter.has("Decor"),
});

// F: control root whose direct write works — no docker call at all.
const callsBefore = dockerCalls;
directWriteFails = false;
await ensureRootMarkers([{ root_id: "Decor2", display_name: "Decor2", server_path: "Decor2" }]);
obs({
  scenario: "F_direct_write_control",
  docker_calls_delta: dockerCalls - callsBefore,
  status: markerStatuses["Decor2"],
});

console.log(JSON.stringify({ observations }, null, 2));
const ok =
  observations[0].docker_calls === 1 &&
  observations[0].backoff_set === true &&
  observations[0].retry_ms_constant === 3_600_000 &&
  observations[1].gate_skipped_docker === true &&
  observations[1].status.error === "docker_write_backoff" &&
  observations[2].docker_calls === 1 &&
  observations[3].retried_once === true &&
  observations[4].backoff_cleared === true &&
  observations[4].status.ok === true &&
  observations[5].docker_calls_delta === 0;
console.log(JSON.stringify({ result: ok ? "PASS" : "FAIL" }));
if (!ok) process.exit(1);
`;

const outFile = join(tmpdir(), "root-marker-backoff-sim.generated.ts");
writeFileSync(outFile, generated, "utf8");
console.log(JSON.stringify({ generated_file: outFile }));
const run = spawnSync(process.execPath, [outFile], { encoding: "utf8" });
process.stdout.write(run.stdout);
process.stderr.write(run.stderr);
process.exit(run.status ?? 1);
