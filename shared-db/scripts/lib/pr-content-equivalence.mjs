// Is the pull request's OWN change the same at two points in time?
//
// WHY THIS EXISTS (orchestrator marker #2758, owner-authorized 2026-09-11)
// ------------------------------------------------------------------------
// Every merge to main forced every other open pull request to merge main, and
// that new head voided its reviewer APPROVE and its merge dispatch. With ~10
// pull requests in flight this was a treadmill of redraws and re-reviews over
// bytes nobody had changed. The fix is to ask the only question that matters:
// did the PULL REQUEST'S OWN DIFF change? A merge from main moves the merge
// base and the head together, so the diff from merge base to head is identical
// when the refresh added nothing of the author's own.
//
// THE COMPARISON IS EXACT, NOT `git patch-id`
// -------------------------------------------
// `git patch-id --stable` ignores whitespace, and whitespace inside a SQL string
// literal is behaviour. So the diff text is compared byte for byte after removing
// only what moves when main moves underneath an unchanged change: `index` blob
// lines and the line NUMBERS in hunk headers. Context lines are kept, so main
// editing next to a pull request hunk counts as a change and needs a review.
//
// `.agent/` IS IGNORED, AND ONE NARROW KIND OF VALUE (#2728)
// ----------------------------------------------------------
// The paired evidence files (`.agent/contract.json`, `.agent/completion.json`)
// are regenerated by every refresh to bind the new head. They describe the
// change; they are not the change. A stored script hash listed in the registry
// on MAIN is set aside only when it equals the sha256 of its source at that same
// commit (see STORED SCRIPT HASHES below). Every other path and byte, including
// rulebooks, workflows and migrations, is compared.
//
// FAIL-CLOSED: every git error answers "not equivalent", never "equivalent".
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'

// `top` anchors at the repository root and the trailing slash limits the match to
// the directory, so only the root `.agent/` tree is excluded: a nested
// `sub/.agent/` path, or a root FILE named `.agent`, is still compared.
export const REFRESH_REGENERATED_PATHSPEC = ':(top,exclude).agent/'

const SHA = /^[0-9a-f]{40}$/
const HEX64 = /^[0-9a-f]{64}$/

export function defaultGit(args, { cwd } = {}) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 512 * 1024 * 1024 })
}

// A digest of the diff between two tree-ish objects, with the moving parts
// removed. Exported so the main-tip freshness gate compares the same way.
// `excludePaths` is used only for registered stored-hash files, which are then
// compared separately in full by `isContentPreservingRefresh`.
export function diffDigest(from, to, { gitRunner = defaultGit, excludeRegenerated = true, excludePaths = [] } = {}) {
  const args = ['-c', 'core.quotepath=false', 'diff', '--no-color', '--no-ext-diff', '--no-textconv', '--no-renames', '--binary', '--full-index', '--src-prefix=a/', '--dst-prefix=b/', from, to, '--', '.']
  if (excludeRegenerated) args.push(REFRESH_REGENERATED_PATHSPEC)
  for (const file of excludePaths) args.push(`:(top,literal,exclude)${file}`)
  const raw = gitRunner(args)
  const normalized = String(raw).split('\n')
    .filter((line) => !/^index [0-9a-f]+\.\.[0-9a-f]+(?: \d+)?$/.test(line))
    .map((line) => line.replace(/^@@ -\d+(?:,\d+)? \+\d+(?:,\d+)? @@/, '@@'))
    .join('\n')
  return createHash('sha256').update(normalized).digest('hex')
}

export function prContentDigest(head, mainRef, { gitRunner = defaultGit, excludePaths = [] } = {}) {
  const base = String(gitRunner(['merge-base', head, mainRef])).trim()
  if (!SHA.test(base)) throw new Error(`could not compute the merge base of ${head} and ${mainRef}`)
  return diffDigest(base, head, { gitRunner, excludePaths })
}

// STORED SCRIPT HASHES (#2728, programme popcre/ai-devops#401 Step 5)
// ------------------------------------------------------------------
// Some reviewed files pin the sha256 of a script (the detector baseline pins
// scripts/production_catalog_verification.py). When main changes that script,
// the pull request must re-pin the hash, and that one-value commit used to void
// every approval (#2860 moved head three times for evidence and hash refreshes).
// The registry of such fields is read from MAIN, never from the pull request, so
// a pull request cannot widen what is set aside. A pinned value is set aside only
// when it equals the LF-normalized sha256 of its source file at that same commit;
// any other value stays in the comparison, so a wrong or hand-edited hash is a
// change. Every other byte of the file is compared at the merge base and at the
// head, so main or the author touching anything else still voids approval.
export const STORED_HASH_REGISTRY_PATH = 'config/review-carry-forward-stored-hashes-v1.json'
const SAFE_PATH = /^(?!\/)(?!.*(?:^|\/)\.\.(?:\/|$))[A-Za-z0-9._/-]+$/

export function readStoredHashRegistry(mainRef, { gitRunner = defaultGit } = {}) {
  let raw
  try { gitRunner(['cat-file', '-e', `${mainRef}:${STORED_HASH_REGISTRY_PATH}`]) } catch { return [] }
  raw = gitRunner(['show', `${mainRef}:${STORED_HASH_REGISTRY_PATH}`])
  let parsed
  try { parsed = JSON.parse(String(raw)) } catch { throw new Error('the stored-hash registry on main is not valid JSON') }
  if (parsed?.schema_version !== 1 || !Array.isArray(parsed.entries)) throw new Error('the stored-hash registry on main has an unknown shape')
  const seen = new Set()
  return parsed.entries.map((entry) => {
    if (!entry || typeof entry !== 'object' || Object.keys(entry).sort().join(',') !== 'field,file,source') throw new Error('each stored-hash registry entry must contain exactly file, field and source')
    for (const key of ['file', 'source']) if (typeof entry[key] !== 'string' || !SAFE_PATH.test(entry[key]) || entry[key].startsWith('.agent/')) throw new Error(`stored-hash registry ${key} is unsafe: ${entry[key]}`)
    if (typeof entry.field !== 'string' || !/^[A-Za-z0-9_]+$/.test(entry.field)) throw new Error('stored-hash registry field name is unsafe')
    const key = `${entry.file}#${entry.field}`
    if (seen.has(key)) throw new Error(`stored-hash registry repeats ${key}`)
    seen.add(key)
    return { file: entry.file, field: entry.field, source: entry.source }
  })
}

function blobAt(commit, file, gitRunner) {
  try { gitRunner(['cat-file', '-e', `${commit}:${file}`]) } catch { return null }
  return String(gitRunner(['show', `${commit}:${file}`]))
}

// The tree entry at one path, read with `git ls-tree` so its type and mode are
// known. The text comparison alone cannot see a mode-only change, and `git show`
// happily prints a tree or a submodule commit where a file was expected.
function treeEntryAt(commit, file, gitRunner) {
  const raw = String(gitRunner(['ls-tree', '-z', '--full-tree', commit, '--', file]))
  const rows = raw.split('\0').filter(Boolean).map((row) => /^(\d{6}) (\w+) ([0-9a-f]{40,64})\t([\s\S]*)$/.exec(row))
  if (rows.some((row) => !row)) throw new Error(`could not parse the tree entry for ${file} at ${commit}`)
  const exact = rows.filter((row) => row[4] === file)
  if (exact.length > 1) throw new Error(`the tree at ${commit} lists ${file} more than once`)
  return exact.length ? { mode: exact[0][1], type: exact[0][2] } : null
}
const REGULAR_FILE_MODES = new Set(['100644', '100755'])

// The file at one commit with only a VERIFIED pinned value replaced by a marker.
// The entry must be a regular file blob; its mode is part of the result, so a
// mode-only change at a stored-hash path is a change.
export function normalizedStoredHashFile(commit, file, entries, { gitRunner = defaultGit } = {}) {
  const entry = treeEntryAt(commit, file, gitRunner)
  if (entry === null) return '<absent>'
  if (entry.type !== 'blob' || !REGULAR_FILE_MODES.has(entry.mode)) throw new Error(`${file} at ${commit} is not a regular file (${entry.mode} ${entry.type})`)
  const text = blobAt(commit, file, gitRunner)
  if (text === null) throw new Error(`${file} at ${commit} is listed but unreadable`)
  let out = `<mode ${entry.mode}>\n${text}`
  for (const entry of entries.filter((row) => row.file === file)) {
    const source = blobAt(commit, entry.source, gitRunner)
    if (source === null) continue
    const digest = createHash('sha256').update(source.replace(/\r\n/g, '\n')).digest('hex')
    const pattern = new RegExp(`("${entry.field}"\\s*:\\s*")([0-9a-f]{64})(")`, 'g')
    const matches = [...out.matchAll(pattern)]
    if (matches.length !== 1 || !HEX64.test(digest) || matches[0][2] !== digest) continue
    out = out.replace(pattern, `$1<verified sha256 of ${entry.source}>$3`)
  }
  return out
}

/**
 * May an APPROVE recorded for `approvedHead` stand for `head`?
 * Only when `approvedHead` is an ancestor of `head` (the history was extended,
 * not rewritten) and the pull request's own diff against its merge base with
 * main is identical at both, `.agent/` evidence and verified stored script-hash
 * re-pins aside. A positive answer carries `implementation_digest`, the digest of
 * the approved implementation, so the carry records what was approved.
 */
export function isContentPreservingRefresh({ approvedHead, head, mainRef = 'origin/main', gitRunner = defaultGit }) {
  const a = String(approvedHead ?? '').toLowerCase(), b = String(head ?? '').toLowerCase()
  if (!SHA.test(a) || !SHA.test(b)) return { ok: false, reason: 'both heads must be exact 40-character SHAs' }
  if (a === b) return { ok: true, reason: 'same head' }
  try { gitRunner(['merge-base', '--is-ancestor', a, b]) } catch (error) {
    return { ok: false, reason: error?.status === 1 ? `${a} is not an ancestor of ${b}; the branch was rewritten, not refreshed` : `could not prove ${a} is an ancestor of ${b}` }
  }
  let registry
  try { registry = readStoredHashRegistry(mainRef, { gitRunner }) } catch (error) {
    return { ok: false, reason: `could not read the stored-hash registry: ${String(error?.message ?? error).split('\n')[0]}` }
  }
  const storedFiles = [...new Set(registry.map((entry) => entry.file))].sort()
  const storedExcludes = storedFiles.map((file) => `:(top,literal,exclude)${file}`)
  // A FILE BOTH SIDES EDITED IS A NEW FILE (grok review of PR #2780). Distant
  // hunks merge cleanly and leave the stripped diff identical, yet the blob at B
  // is not the blob that was reviewed at A. So if main, between the two merge
  // bases, touched any path the pull request changes, nothing is carried.
  // Registered stored-hash files are compared in full below instead, at both
  // merge bases and both heads, so they need no path test here.
  let baseA, baseB
  try {
    const mergeBase = (sha) => { const base = String(gitRunner(['merge-base', sha, mainRef])).trim(); if (!SHA.test(base)) throw new Error(`could not compute the merge base of ${sha} and ${mainRef}`); return base }
    const names = (from, to) => String(gitRunner(['-c', 'core.quotepath=false', 'diff', '--name-only', '--no-renames', from, to, '--', '.', REFRESH_REGENERATED_PATHSPEC, ...storedExcludes])).split('\n').map((line) => line.trim()).filter(Boolean)
    baseA = mergeBase(a); baseB = mergeBase(b)
    const prPaths = new Set([...names(baseA, a), ...names(baseB, b)])
    const shared = baseA === baseB ? [] : names(baseA, baseB).filter((path) => prPaths.has(path))
    if (shared.length) return { ok: false, reason: `main changed ${shared.slice(0, 5).join(', ')}, which the pull request also changes; the combined file needs a new review` }
  } catch (error) {
    return { ok: false, reason: `could not compare the paths main changed: ${String(error?.message ?? error).split('\n')[0]}` }
  }
  let before, after, storedBefore, storedAfter
  try {
    before = prContentDigest(a, mainRef, { gitRunner, excludePaths: storedFiles }); after = prContentDigest(b, mainRef, { gitRunner, excludePaths: storedFiles })
    // Only registered files the pull request itself changes are part of its diff;
    // one it leaves untouched at a head is not its content, whatever main did to it.
    const stored = (base, tip) => storedFiles.map((file) => [file, normalizedStoredHashFile(base, file, registry, { gitRunner }), normalizedStoredHashFile(tip, file, registry, { gitRunner })]).filter(([, from, to]) => from !== to)
    storedBefore = JSON.stringify(stored(baseA, a)); storedAfter = JSON.stringify(stored(baseB, b))
  } catch (error) {
    return { ok: false, reason: `could not read the pull request diff: ${String(error?.message ?? error).split('\n')[0]}` }
  }
  if (before !== after) return { ok: false, reason: `the pull request's own diff changed between ${a} and ${b}` }
  if (storedBefore !== storedAfter) return { ok: false, reason: `the pull request's own diff changed between ${a} and ${b} in a file that pins a script hash; only a re-pin to the verified source hash is carried` }
  const implementationDigest = createHash('sha256').update(`${before}\n${storedBefore}`).digest('hex')
  return { ok: true, reason: `the pull request's own diff is identical at ${a} and ${b} (.agent evidence and verified script-hash re-pins aside)`, implementation_digest: implementationDigest }
}
