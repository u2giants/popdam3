// Is the pull request's OWN change the same at two points in time?
//
// WHY THIS EXISTS (orchestrator marker #2758, owner-authorized 2026-09-11)
// ------------------------------------------------------------------------
// Every merge to main forced every other open pull request to merge main, and
// that new head voided its reviewer APPROVE and its merge dispatch. With ~10
// pull requests in flight this was a treadmill of redraws and re-reviews over
// bytes nobody had changed. The fix is to ask the only question that matters:
// did the PULL REQUEST'S OWN DIFF change? A merge from main moves the merge
// base and the head together, so the diff from merge base to head is identical
// when the refresh added nothing of the author's own.
//
// THE COMPARISON IS EXACT, NOT `git patch-id`
// -------------------------------------------
// `git patch-id --stable` ignores whitespace, and whitespace inside a SQL string
// literal is behaviour. So the diff text is compared byte for byte after removing
// only what moves when main moves underneath an unchanged change: `index` blob
// lines and the line NUMBERS in hunk headers. Context lines are kept, so main
// editing next to a pull request hunk counts as a change and needs a review.
//
// `.agent/` IS IGNORED, AND NOTHING ELSE IS
// -----------------------------------------
// The paired evidence files (`.agent/contract.json`, `.agent/completion.json`)
// are regenerated by every refresh to bind the new head. They describe the
// change; they are not the change. Every other path, including rulebooks,
// workflows and migrations, is compared.
//
// FAIL-CLOSED: every git error answers "not equivalent", never "equivalent".
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'

// `top` anchors at the repository root and the trailing slash limits the match to
// the directory, so only the root `.agent/` tree is excluded: a nested
// `sub/.agent/` path, or a root FILE named `.agent`, is still compared.
export const REFRESH_REGENERATED_PATHSPEC = ':(top,exclude).agent/'

const SHA = /^[0-9a-f]{40}$/

export function defaultGit(args, { cwd } = {}) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 512 * 1024 * 1024 })
}

// A digest of the diff between two tree-ish objects, with the moving parts
// removed. Exported so the main-tip freshness gate compares the same way.
export function diffDigest(from, to, { gitRunner = defaultGit, excludeRegenerated = true } = {}) {
  const args = ['-c', 'core.quotepath=false', 'diff', '--no-color', '--no-ext-diff', '--no-textconv', '--no-renames', '--binary', '--full-index', '--src-prefix=a/', '--dst-prefix=b/', from, to, '--', '.']
  if (excludeRegenerated) args.push(REFRESH_REGENERATED_PATHSPEC)
  const raw = gitRunner(args)
  const normalized = String(raw).split('\n')
    .filter((line) => !/^index [0-9a-f]+\.\.[0-9a-f]+(?: \d+)?$/.test(line))
    .map((line) => line.replace(/^@@ -\d+(?:,\d+)? \+\d+(?:,\d+)? @@/, '@@'))
    .join('\n')
  return createHash('sha256').update(normalized).digest('hex')
}

export function prContentDigest(head, mainRef, { gitRunner = defaultGit } = {}) {
  const base = String(gitRunner(['merge-base', head, mainRef])).trim()
  if (!SHA.test(base)) throw new Error(`could not compute the merge base of ${head} and ${mainRef}`)
  return diffDigest(base, head, { gitRunner })
}

/**
 * May an APPROVE recorded for `approvedHead` stand for `head`?
 * Only when `approvedHead` is an ancestor of `head` (the history was extended,
 * not rewritten) and the pull request's own diff against its merge base with
 * main is identical at both, `.agent/` evidence aside.
 */
export function isContentPreservingRefresh({ approvedHead, head, mainRef = 'origin/main', gitRunner = defaultGit }) {
  const a = String(approvedHead ?? '').toLowerCase(), b = String(head ?? '').toLowerCase()
  if (!SHA.test(a) || !SHA.test(b)) return { ok: false, reason: 'both heads must be exact 40-character SHAs' }
  if (a === b) return { ok: true, reason: 'same head' }
  try { gitRunner(['merge-base', '--is-ancestor', a, b]) } catch (error) {
    return { ok: false, reason: error?.status === 1 ? `${a} is not an ancestor of ${b}; the branch was rewritten, not refreshed` : `could not prove ${a} is an ancestor of ${b}` }
  }
  // A FILE BOTH SIDES EDITED IS A NEW FILE (grok review of PR #2780). Distant
  // hunks merge cleanly and leave the stripped diff identical, yet the blob at B
  // is not the blob that was reviewed at A. So if main, between the two merge
  // bases, touched any path the pull request changes, nothing is carried.
  try {
    const mergeBase = (sha) => { const base = String(gitRunner(['merge-base', sha, mainRef])).trim(); if (!SHA.test(base)) throw new Error(`could not compute the merge base of ${sha} and ${mainRef}`); return base }
    const names = (from, to) => String(gitRunner(['-c', 'core.quotepath=false', 'diff', '--name-only', '--no-renames', from, to, '--', '.', REFRESH_REGENERATED_PATHSPEC])).split('\n').map((line) => line.trim()).filter(Boolean)
    const baseA = mergeBase(a), baseB = mergeBase(b)
    const prPaths = new Set([...names(baseA, a), ...names(baseB, b)])
    const shared = baseA === baseB ? [] : names(baseA, baseB).filter((path) => prPaths.has(path))
    if (shared.length) return { ok: false, reason: `main changed ${shared.slice(0, 5).join(', ')}, which the pull request also changes; the combined file needs a new review` }
  } catch (error) {
    return { ok: false, reason: `could not compare the paths main changed: ${String(error?.message ?? error).split('\n')[0]}` }
  }
  let before, after
  try { before = prContentDigest(a, mainRef, { gitRunner }); after = prContentDigest(b, mainRef, { gitRunner }) } catch (error) {
    return { ok: false, reason: `could not read the pull request diff: ${String(error?.message ?? error).split('\n')[0]}` }
  }
  return before === after
    ? { ok: true, reason: `the pull request's own diff is identical at ${a} and ${b} (.agent evidence aside)` }
    : { ok: false, reason: `the pull request's own diff changed between ${a} and ${b}` }
}
