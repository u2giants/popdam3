CREATE TABLE IF NOT EXISTS dflow.sample_shipment (
  sample_shipment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carrier_id smallint REFERENCES dflow.sample_carrier(sample_carrier_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  tracking_number text CHECK (tracking_number IS NULL OR btrim(tracking_number) <> ''),
  origin_location_type text NOT NULL CHECK (origin_location_type IN ('factory','office','customer','warehouse')),
  origin_location_id text NOT NULL CHECK (btrim(origin_location_id) <> ''),
  destination_location_type text NOT NULL CHECK (destination_location_type IN ('factory','office','customer','warehouse')),
  destination_location_id text NOT NULL CHECK (btrim(destination_location_id) <> ''),
  state text NOT NULL DEFAULT 'draft' CHECK (state IN (
    'draft','packed','shipped','received','delivered_reported','delivery_exception','cancelled'
  )),
  shipped_at timestamptz,
  received_at timestamptz,
  actor_user text NOT NULL CHECK (btrim(actor_user) <> ''),
  actor_role text NOT NULL CHECK (btrim(actor_role) <> ''),
  idempotency_key text NOT NULL UNIQUE CHECK (btrim(idempotency_key) <> ''),
  request_hash text NOT NULL CHECK (btrim(request_hash) <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (origin_location_type <> destination_location_type OR origin_location_id <> destination_location_id),
  CHECK ((carrier_id IS NULL) = (tracking_number IS NULL)),
  CHECK (state NOT IN ('shipped','received','delivered_reported','delivery_exception') OR shipped_at IS NOT NULL),
  CHECK (state <> 'received' OR received_at IS NOT NULL)
);

