CREATE TABLE IF NOT EXISTS dflow.sample_carrier (
  sample_carrier_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carrier_code text NOT NULL UNIQUE CHECK (carrier_code = lower(carrier_code) AND btrim(carrier_code) <> ''),
  display_name text NOT NULL UNIQUE CHECK (btrim(display_name) <> ''),
  tracking_url_template text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

