-- 19. plm.sesame_style_guide_character -- THE ONLY DERIVED TABLE, LABELLED AS SUCH.
--
-- THE PORTAL DOES NOT STATE THIS LINK. We reconstruct it, and the whole design of this
-- table exists to stop that reconstruction from ever being mistaken for portal fact:
--
--   * relationship_truth is pinned to 'derived' by a CHECK that permits NO other value,
--     so a row here can never be laundered into a declared fact by an UPDATE that does
--     not exist or a later migration that forgets.
--   * derivation_method is pinned to 'single_guide_asset' by a CHECK that permits no
--     other value. It names the rule in the row itself. A second rule requires a schema
--     change and therefore an issue and a reviewer.
--   * rule_version is required, so the exact revision of the derivation that produced a
--     row is recoverable years later.
--
-- THE RULE, AND WHAT IT REFUSES. Rows are built ONLY from assets carrying EXACTLY ONE
-- style guide. Thousands of assets in this capture carry two or more guides at once; on
-- those, the characters cannot be attributed to any one guide, so their character rows
-- are EXCLUDED, NOT GUESSED. The number excluded is recorded on the capture in
-- plm.sesame_capture.guide_character_rows_excluded so the gap between this table and the
-- asset evidence is a stated number rather than an invisible one.
--
-- WHAT IS REFUSED OUTRIGHT, AND HAS NO TABLE ANYWHERE IN THIS SCHEMA: brand-to-character.
-- The same "exactly one" trick would produce a brand roster that looks just as tidy, and
-- it would be fabrication -- the portal never states the relationship at all, and the
-- brand and character fields on a shared asset are INDEPENDENT. That is precisely the
-- Disney DCP Vault error. It is refused by policy, asserted by a DO block at the end of
-- this file, and asserted again by the contract tests.
--
-- THE TWO *_field_generation COLUMNS ARE NOT DECORATION. The schema contract requires
-- composite foreign keys onto the CURRENT generation of each vocabulary. The vocabulary
-- key is (capture_id, field_generation, value_key), so an FK onto its current generation
-- is only expressible in PostgreSQL with a column on this side holding that generation.
-- Both are pinned to 'current' by a CHECK, so they cannot drift and cannot be used to
-- sneak a legacy-generation derivation in through the side door.
-- =====================================================================================
