-- 9. plm.sesame_category -- THE ONE DECLARED HIERARCHY IN THIS PORTAL.
--
-- This is the only axis with a genuine portal-issued identity AND a genuine portal-stated
-- hierarchy: the API returns each node's own id, its parent, its path and its ancestors.
-- Storing the tree is therefore repeating what the licensor said, not inferring it.
--
-- THE OUT-OF-PORTAL NODES LAND. A minority of these nodes are the DAM's own internal
-- folders and are not licensing content at all. They are kept because the tree cannot be
-- resolved without them -- an in-portal node can have an out-of-portal ancestor -- and
-- because their presence is the PROOF that the scope limit was real rather than a filter
-- somebody remembered to apply. They carry in_licensee_portal = false and no consumer may
-- treat them as licensed content.
--
-- is_guide_level MARKS A FOLDER THAT IS AN INDIVIDUAL STYLE GUIDE. It is deliberately NOT
-- a foreign key to plm.sesame_style_guide; see the header of that table.
--
-- THE SELF-REFERENCING FOREIGN KEY IS DEFERRABLE INITIALLY DEFERRED because a loader
-- cannot in general insert a tree parents-first without walking it twice; the constraint
-- is checked at COMMIT, when the whole capture is present. It is composite on
-- (capture_id, parent_category_source_id) so a node can never point at a parent belonging
-- to a DIFFERENT capture. MATCH SIMPLE means a NULL parent (the roots) skips the check,
-- which is the wanted behaviour.
-- =====================================================================================
