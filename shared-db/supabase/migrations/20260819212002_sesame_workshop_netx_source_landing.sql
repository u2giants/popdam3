-- u2giants/shared-db is a PUBLIC repository. This extract is licensed source data held in
-- the PRIVATE repo u2giants/licensor-source-data. No brand, sub-brand, character, style
-- guide, art style, theme, category, asset, file name, title, keyword or raw payload
-- value may ever appear in this file, in a contract test, in CI output, or in a pull
-- request or issue on this repository.
--   SCHEMA IN GIT. DATA OUT OF GIT.
-- Rows arrive at runtime from the private loader through the INSERT grants below. The
-- contract tests use INVENTED fixture values only (ZZTEST-*, example.invalid).
--
-- WHAT THIS IS
--   A lossless, append-only, capture-scoped landing of ONE capture of a NetX DAM licensee
--   portal. Every source table is keyed by `capture_id`, so a refresh ADDS a snapshot and
--   never overwrites or deletes an earlier one. Retry safety is `on conflict do nothing`,
--   which needs no UPDATE privilege.
--
-- WHAT THIS DELIBERATELY IS NOT
--   It creates, renames, updates, merges and deletes NOTHING in core.* or dam.*. It
--   resolves NOTHING: this release ships no reconciliation columns at all, so there is no
--   half-built resolution surface to misread. Nothing here is canonical.
--
-- FOUR PORTAL FACTS THIS SHAPE EXISTS TO SURVIVE
--
--   1. THE PORTAL CARRIES TWO LIVE GENERATIONS OF THE SAME FIELD. Several axes exist
--      twice on the same asset: a legacy free-text lowercase version and a curated
--      proper-cased version, with DIFFERENT value sets and DIFFERENT cardinalities. A
--      schema that keeps only one generation destroys evidence; a schema that merges them
--      fabricates identity. Both land, in the same table, separated by
--      `field_generation`, which is part of every primary key so the two can never
--      collapse onto each other by case folding. NOTHING in this schema joins the two
--      generations together; that mapping is a business ruling, not a landing concern.
--
--   2. VOCABULARY VALUES ARE THE ONLY IDENTITY THERE IS. NetX issues numeric IDs for
--      CATEGORIES and ASSETS only. The brand, sub-brand, character, style-guide,
--      art-style, asset-type and theme values arrive as STRINGS on the asset record and
--      the portal's own choice-list API returns empty for every one of them. Identity on
--      those axes is therefore `value_key`, a normalized label GENERATED BY US. There is
--      deliberately NO source-ID column on those tables: a nullable, permanently empty
--      `source_value_id` would read as "the portal has one and we did not capture it".
--
--   3. MULTI-VALUED FIELDS ARRIVE AS ONE CSV-QUOTED STRING, while a single value arrives
--      bare and unquoted. A loader that splits on commas unconditionally SHATTERS single
--      values that legitimately contain a comma; a loader that never splits COLLAPSES
--      every multi-valued asset to one bogus value. Neither failure is visible in a row
--      count. `multivalue_parse_verified` on the capture is the loader's claim that it
--      parsed correctly, and section D of plm.complete_sesame_capture is the EVIDENCE
--      behind that claim.
--
--   4. A STYLE GUIDE EXISTS IN TWO INCOMPATIBLE FORMS AT ONCE: as a FOLDER in the
--      category tree (plm.sesame_category.is_guide_level) and as a VALUE in the asset's
--      style-guide field (plm.sesame_style_guide). Only a small minority of the field
--      values match a folder name exactly. THEY ARE NOT THE SAME OBJECT. Both land and
--      `is_guide_level` is deliberately NOT a foreign key to plm.sesame_style_guide. The
--      correspondence is left unresolved for a human ruling.
--
-- DECLARED FACT vs RECONSTRUCTED, AND THE ONE LINK THAT IS REFUSED OUTRIGHT
--   Declared by the portal and stored as fact: the category tree (the API states `path`
--   and `ancestors`), asset-to-category membership, and every value the portal stamped on
--   an asset. All of those carry relationship_truth = 'declared', pinned by a CHECK that
--   permits no other value.
--
--   Reconstructed by us, kept strictly separate, and pinned to
--   relationship_truth = 'derived' by a CHECK that permits no other value:
--   plm.sesame_style_guide_character ONLY. It is built exclusively from assets carrying
--   EXACTLY ONE style guide. Assets carrying two or more guides at once cannot be split,
--   and the character rows behind them are EXCLUDED, not guessed; their count is recorded
--   on the capture in `guide_character_rows_excluded` so the gap is auditable rather than
--   invisible. This is the ONLY derived table in the schema; any future derived link
--   needs its own issue and its own justification.
--
--   REFUSED: there is NO brand-to-character table in this schema, derived or otherwise,
--   and none may be added. The portal NEVER states which characters belong to which
--   brand; thousands of assets carry no character at all and a further thousand carry no
--   brand. Pairing two independent fields on a shared asset is exactly the Disney DCP
--   Vault fabrication this project has already paid for once. A DO block near the end of
--   this file, and section A of the contract tests, both fail if such a table appears.
--   If that roster is ever needed it is a business ruling made against the asset
--   evidence, not a stored fact.
--
-- THE SCOPE LIMIT IS PART OF THE DATA, NOT A FILTER APPLIED TO IT
--   A minority of the category nodes are the DAM's own internal folders and sit outside
--   the licensee portal entirely. They LAND -- they are needed to resolve parent IDs on
--   the tree and to prove the scope limit was real -- but they carry
--   `in_licensee_portal = false` and must never be treated as licensing content.
--
-- IMMUTABILITY IS DELIVERED BY PRIVILEGE SEPARATION, NOT BY TRIGGERS
--   Same mechanism, and the same reason, as the NBCU, WildBrain, Sega and Peanuts
--   landings. This database has been burned by a BEFORE trigger that read a
--   GENERATED ... STORED column, which Postgres populates AFTER before-triggers fire: the
--   guard never fired and nothing ever raised. Privilege separation fails closed and is
--   INSPECTABLE in information_schema.role_table_grants, so a contract test can assert
--   the guarantee itself rather than assert that some guard code exists.
--
--   THE TRAP THAT MADE 20260810080000 NECESSARY IS HANDLED IN THIS FILE. The schema `plm`
--   carries `ALTER DEFAULT PRIVILEGES ... GRANT ALL ON TABLES TO service_role`, so every
--   table below is BORN holding UPDATE, DELETE and TRUNCATE for service_role and a bare
--   `grant select, insert` is a no-op. The explicit REVOKE block near the end is what
--   actually makes these rows immutable, and the assertion block after it fails the
--   migration if the revokes did not take.
--
--   Every privilege statement below is written out IN FULL, one per table, statically and
--   schema-qualified. No `DO` loop, no `execute format(...)`. Dynamic privilege SQL hides
--   the privilege model from the cross-PR object guard and from every human reader, and
--   was rejected on the Sega landing (#1196) for exactly that reason.
--
-- THE WRITE PATH TO THE CAPTURE ROOT
--   service_role holds SELECT ONLY on plm.sesame_capture. Capture rows are created and
--   transitioned exclusively by plm.begin_sesame_capture and plm.complete_sesame_capture
--   below, both `security definer` with a pinned search_path and EXECUTE granted only to
--   service_role. Never grant INSERT on plm.sesame_capture to service_role: that would
--   let a loader mint a capture that skipped every validation those functions perform.
--   The completion rule is enforced BOTH in complete_ and as a table CHECK
--   (sesame_capture_complete_requirements_chk), so it still holds against a writer that
--   reaches the table some other way and does not depend on the functions being correct.
--
-- Depends on (exact 14-digit versions):
--   20260621150714  foundation  -- schema plm
--   20260621150815  app_core    -- app.has_role / has_any_role / has_app_access
-- =====================================================================================


-- =====================================================================================
-- 1. plm.sesame_capture -- one row per attempted load. The root of every snapshot.
--
-- capture_key is the loader's idempotency key.
--
-- source_commit_sha vs read_commit_sha are TWO DIFFERENT FACTS and must not be collapsed.
-- source_commit_sha identifies the DATA -- the private-repo commit the extract was merged
-- at. read_commit_sha is the commit the loader actually had checked out when it read the
-- bytes, which can be a LATER commit that changed only documentation.
--
-- category_tree_walked IS NOT CEREMONY. The portal's faceted search IS NOT RECURSIVE:
-- asking a PARENT folder for its assets returns a size of ZERO with HTTP 200 even when
-- its children hold thousands of assets. A crawler that queries only the top folders
-- therefore produces an EMPTY-LOOKING BUT ENTIRELY SUCCESSFUL capture -- no error, no
-- timeout, no partial-page marker. The flag may be set only after EVERY node has been
-- queried individually, and plm.complete_sesame_capture additionally requires
-- categories_visited to equal the loaded category row count, so the flag cannot be a
-- bare assertion.
-- =====================================================================================
create table plm.sesame_capture (
  id                            uuid        primary key default gen_random_uuid(),
  capture_key                   text        not null unique,
  source_repository             text        not null,
  source_commit_sha             text        not null,
  read_commit_sha               text            null,
  source_manifest_sha256        text        not null,
  portal_base_url               text        not null,
  portal_slug                   text        not null,
  source_captured_at            timestamptz not null,
  load_started_at               timestamptz not null default now(),
  load_completed_at             timestamptz     null,
  status                        text        not null default 'loading',
  expected_counts               jsonb       not null,
  observed_counts               jsonb       not null default '{}'::jsonb,
  media_downloaded              integer     not null default 0,
  category_tree_walked          boolean     not null default false,
  categories_visited            integer     not null default 0,
  pagination_verified           boolean     not null default false,
  multivalue_parse_verified     boolean     not null default false,
  guide_character_rows_excluded integer     not null default 0,
  error_summary                 jsonb       not null default '[]'::jsonb,
  raw_summary                   jsonb       not null,
  created_by                    text        not null,

  constraint sesame_capture_status_chk
    check (status in ('loading','complete','rejected','abandoned')),
  constraint sesame_capture_key_nonblank_chk         check (btrim(capture_key) <> ''),
  constraint sesame_capture_repository_nonblank_chk  check (btrim(source_repository) <> ''),
  constraint sesame_capture_portal_nonblank_chk      check (btrim(portal_base_url) <> ''),
  constraint sesame_capture_portal_slug_nonblank_chk check (btrim(portal_slug) <> ''),
  constraint sesame_capture_created_by_nonblank_chk  check (btrim(created_by) <> ''),
  constraint sesame_capture_commit_sha_chk
    check (source_commit_sha ~ '^[0-9a-f]{40}$'),
  constraint sesame_capture_read_commit_sha_chk
    check (read_commit_sha is null or read_commit_sha ~ '^[0-9a-f]{40}$'),
  constraint sesame_capture_manifest_sha256_chk
    check (source_manifest_sha256 ~ '^[0-9a-f]{64}$'),
  -- Scope guard, not a style preference: this project may never download portal media.
  -- This is the constraint that makes the media clause of
  -- sesame_capture_complete_requirements_chk below, and the media_downloaded_nonzero
  -- branch of plm.complete_sesame_capture, UNREACHABLE in normal operation. Both are kept
  -- deliberately as defence in depth for a future in which this line is dropped; see the
  -- note on that branch in the function.
  constraint sesame_capture_media_zero_chk           check (media_downloaded = 0),
  constraint sesame_capture_categories_visited_nonneg_chk
    check (categories_visited >= 0),
  constraint sesame_capture_guide_char_excluded_nonneg_chk
    check (guide_character_rows_excluded >= 0),
  constraint sesame_capture_complete_time_chk
    check ((status = 'complete') = (load_completed_at is not null)),
  -- The completion rule from the schema contract, enforced by the TABLE and not only by a
  -- function, so a writer that reaches this table another way still cannot mint a
  -- 'complete' capture that never walked the tree, never verified pagination, never
  -- proved its multi-value parse, downloaded media, or carried validation errors.
  --
  -- categories_visited = category row count is DELIBERATELY NOT here: a table CHECK may
  -- not read another table. It is enforced in plm.complete_sesame_capture section A and
  -- has its own contract test.
  constraint sesame_capture_complete_requirements_chk
    check (
      status <> 'complete'
      or (
        load_completed_at is not null
        and category_tree_walked = true
        and pagination_verified = true
        and multivalue_parse_verified = true
        and media_downloaded = 0
        and jsonb_array_length(error_summary) = 0
      )
    ),
  constraint sesame_capture_expected_counts_obj_chk
    check (jsonb_typeof(expected_counts) = 'object'),
  constraint sesame_capture_observed_counts_obj_chk
    check (jsonb_typeof(observed_counts) = 'object'),
  constraint sesame_capture_error_summary_arr_chk
    check (jsonb_typeof(error_summary) = 'array'),
  constraint sesame_capture_raw_summary_obj_chk
    check (jsonb_typeof(raw_summary) = 'object')
);

