  constraint sesame_category_capture_fkey
    foreign key (capture_id) references plm.sesame_capture (id) on delete restrict,
  constraint sesame_category_path_uniq unique (capture_id, category_path),
  constraint sesame_category_parent_fkey
    foreign key (capture_id, parent_category_source_id)
    references plm.sesame_category (capture_id, category_source_id)
    on delete restrict
    deferrable initially deferred,
  -- A node may not be its own parent. The deferred FK above would happily accept that.
  constraint sesame_category_not_self_parent_chk
    check (parent_category_source_id is null
           or parent_category_source_id <> category_source_id),
  constraint sesame_category_label_nonblank_chk check (btrim(category_label) <> ''),
  constraint sesame_category_path_nonblank_chk  check (btrim(category_path) <> ''),
  constraint sesame_category_depth_nonneg_chk   check (depth >= 0),
  constraint sesame_category_child_count_nonneg_chk check (child_count >= 0),
  -- DELIBERATELY ABSENT: a `(depth = 0) = (parent is null)` coupling. It looks obviously
  -- right and it is a guess -- the schema contract states only that depth is
  -- non-negative, and nothing in the source documentation fixes whether the portal counts
  -- its roots from 0 or from 1. A constraint built on the wrong convention would reject
  -- EVERY node of a perfectly good capture, which is a far worse outcome than the modest
  -- guard it would buy. If the convention is ever established, it is a one-line follow-up.
  constraint sesame_category_raw_obj_chk check (jsonb_typeof(raw) = 'object')
);
create index sesame_category_parent_idx
