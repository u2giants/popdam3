-- =====================================================================================
-- FUNCTIONS -- the sole write path to plm.sesame_capture.
--
-- All three are `security definer` with a pinned search_path, EXECUTE revoked from public.
-- begin_ and complete_ are granted ONLY to service_role, which can otherwise only READ
-- the capture root.
--
-- THE COUNT-VALIDATION RULE, AND WHY IT IS WRITTEN THE LONG WAY IN FOUR SEPARATE
-- BRANCHES. Four live defects were found by falsifying this exact code in the sibling
-- landings and closed in 20260819112524 and 20260819123658. Every one is a shape a
-- shorter version accepts:
--
--   (1) A JSON `null` IS NOT A MISSING KEY. `v_exp ? 'assets'` is TRUE for
--       {"assets": null}, so a presence test reports the count as supplied, while the
--       resulting SQL NULL makes every comparison UNKNOWN and therefore never false. The
--       count check is SKIPPED and a truncated capture publishes as complete.
--
--   (2) `(v_exp ->> key)::bigint` CASTS THE TEXT OF THE JSON NUMBER. A perfectly legal
--       integral JSON number written 1.0 renders as the text '1.0' and raises `invalid
--       input syntax for type bigint`; a value past bigint raises out-of-range. Either
--       aborts the function BEFORE the rejection row is written, wedging the capture in
--       `loading` with NO recorded reason. This file range-refuses BY NAME first and then
--       assigns through `::numeric::bigint`, which accepts 1.0 and cannot overflow
--       because the range was already proven.
--
--   (3) A NUMERIC-LOOKING JSON STRING is the most dangerous of the four, because it is a
--       silent WRONG ANSWER rather than a crash: {"assets": "12"} yields the text '12',
--       which casts cleanly and compares equal, so a manifest that lost its types
--       publishes as though it had been checked. It is refused by an explicit
--       `jsonb_typeof(...) <> 'number'` test, and the contract test that proves it uses a
--       string whose numeric value MATCHES the true row count -- a fixture using "999"
--       would pass on the mismatch and prove nothing.
--
--   (4) THE NARROW-COLUMN TRAP. A value between the integer and bigint limits raises
--       `integer out of range` on a comparison against an `integer` column. Every
--       integer-typed capture column compared here is cast to bigint FIRST, and the
--       incoming argument is range-refused by name before any cast.
--
-- EACH TEST IS ITS OWN BRANCH. SQL does not promise to short-circuit `or`, so a single
-- combined predicate can evaluate a cast on a value the type test was supposed to have
-- rejected and die with a raw cast error instead of the named code. The type test must
-- have FINISHED before anything casts.
--
-- AND IT IS ENFORCED TWICE. begin_ refuses a bad manifest at the start; complete_
-- re-reads the STORED object and refuses it again, because an owner-level UPDATE can
-- reach plm.sesame_capture.expected_counts without going through begin_ at all.
-- =====================================================================================

create or replace function plm.begin_sesame_capture(
  p_capture_key            text,
  p_source_repository      text,
  p_source_commit_sha      text,
  p_source_manifest_sha256 text,
  p_portal_base_url        text,
  p_portal_slug            text,
  p_source_captured_at     timestamptz,
  p_expected_counts        jsonb,
  p_raw_summary            jsonb,
  p_created_by             text,
  p_read_commit_sha        text default null
) returns uuid
language plpgsql
security definer
set search_path = plm, pg_temp
as $$
declare
  v_existing plm.sesame_capture%rowtype;
  v_id       uuid;
begin
  -- Validate before touching anything. A malformed argument must fail here, loudly,
  -- rather than land a half-described capture the publication gate then has to reason
  -- about. Raising is correct at THIS end: no capture row exists yet, so there is nothing
  -- to record a refusal on and nothing can be wedged.
  if p_capture_key is null or btrim(p_capture_key) = '' then
    raise exception 'begin_sesame_capture: capture_key is required';
  end if;
  if p_source_repository is null or btrim(p_source_repository) = '' then
    raise exception 'begin_sesame_capture: source_repository is required';
  end if;
  if p_portal_base_url is null or btrim(p_portal_base_url) = '' then
    raise exception 'begin_sesame_capture: portal_base_url is required';
  end if;
  if p_portal_slug is null or btrim(p_portal_slug) = '' then
    raise exception 'begin_sesame_capture: portal_slug is required';
  end if;
  if p_created_by is null or btrim(p_created_by) = '' then
    raise exception 'begin_sesame_capture: created_by is required';
  end if;
  if p_source_captured_at is null then
    raise exception 'begin_sesame_capture: source_captured_at is required';
  end if;
  if p_source_commit_sha is null or p_source_commit_sha !~ '^[0-9a-f]{40}$' then
    raise exception
      'begin_sesame_capture: source_commit_sha must be 40 lowercase hex characters';
  end if;
  if p_read_commit_sha is not null and p_read_commit_sha !~ '^[0-9a-f]{40}$' then
    raise exception
      'begin_sesame_capture: read_commit_sha must be 40 lowercase hex characters';
  end if;
  if p_source_manifest_sha256 is null or p_source_manifest_sha256 !~ '^[0-9a-f]{64}$' then
    raise exception
      'begin_sesame_capture: source_manifest_sha256 must be 64 lowercase hex characters';
  end if;
  if p_expected_counts is null or jsonb_typeof(p_expected_counts) <> 'object'
     or p_expected_counts = '{}'::jsonb then
    raise exception
      'begin_sesame_capture: expected_counts must be a non-empty JSON object';
  end if;

  -- (3) then (1): the TYPE test, ALONE, FIRST. This rejects a JSON null, a string --
  -- INCLUDING a numeric-looking one such as "12", which would otherwise cast cleanly and
  -- compare equal -- a boolean, an object and an array.
  if exists (
    select 1 from jsonb_each(p_expected_counts) e
     where jsonb_typeof(e.value) <> 'number'
  ) then
    raise exception
      'begin_sesame_capture: every expected_counts value must be a JSON NUMBER that is a non-negative integer; a null, a numeric-looking STRING such as "12", a boolean, an object or an array would either skip that count check at the publication gate or pass it on an untyped value; got %',
      p_expected_counts;
  end if;
  -- Only now, with every value proven to be a number, may anything cast.
  if exists (
    select 1 from jsonb_each(p_expected_counts) e
     where (e.value #>> '{}')::numeric < 0
        or (e.value #>> '{}')::numeric <> trunc((e.value #>> '{}')::numeric)
  ) then
    raise exception
      'begin_sesame_capture: every expected_counts value must be a non-negative integer; got %',
      p_expected_counts;
  end if;
  -- (2) and (4): refuse an out-of-range count with a NAMED message rather than letting a
  -- later `::bigint` raise a bare out-of-range and wedge the capture in `loading`.
  if exists (
    select 1 from jsonb_each(p_expected_counts) e
     where (e.value #>> '{}')::numeric > 9223372036854775807::numeric
  ) then
    raise exception
      'begin_sesame_capture: an expected_counts value exceeds the maximum representable count (9223372036854775807); got %',
      p_expected_counts;
  end if;

  if p_raw_summary is null or jsonb_typeof(p_raw_summary) <> 'object' then
    raise exception 'begin_sesame_capture: raw_summary must be a JSON object';
  end if;

  -- Zero-media scope. The table pins media_downloaded to zero; a manifest that CLAIMS a
  -- nonzero media count disagrees with this schema, and that must stop the load. Every
  -- value is already proven to be a non-negative in-range JSON number by the three tests
  -- above, so this comparison cannot raise.
  if (p_expected_counts ? 'media_downloaded')
     and (p_expected_counts ->> 'media_downloaded')::numeric <> 0 then
    raise exception
      'begin_sesame_capture: expected_counts.media_downloaded must be 0; this project never downloads media';
  end if;

  -- Serialize concurrent starts of the SAME capture_key. Two loader processes racing here
  -- would otherwise both miss the select and both insert.
  perform pg_advisory_xact_lock(
    hashtextextended('plm.sesame_capture:' || p_capture_key, 0));

  select * into v_existing from plm.sesame_capture where capture_key = p_capture_key;

  if found then
    -- Same key, different bytes, is a CONTRADICTION, not a resume. Silently appending
    -- different source data under an existing capture key would make the snapshot
    -- unreconstructable.
    if v_existing.source_manifest_sha256 is distinct from p_source_manifest_sha256 then
      raise exception
        'begin_sesame_capture: capture_key % already exists with a DIFFERENT source manifest hash; refusing',
        p_capture_key;
    end if;
    if v_existing.source_commit_sha is distinct from p_source_commit_sha then
      raise exception
        'begin_sesame_capture: capture_key % already exists with a DIFFERENT source commit sha; refusing',
        p_capture_key;
    end if;
    if v_existing.source_repository is distinct from p_source_repository
       or v_existing.portal_base_url is distinct from p_portal_base_url
       or v_existing.portal_slug is distinct from p_portal_slug
       or v_existing.source_captured_at is distinct from p_source_captured_at then
      raise exception
        'begin_sesame_capture: capture_key % already exists with a DIFFERENT source identity; refusing',
        p_capture_key;
    end if;

    if v_existing.status = 'complete' then
      -- Idempotent: hand back the finished capture untouched. Never re-open it.
      return v_existing.id;
    elsif v_existing.status = 'loading' then
      -- Resume. Only the loader's own read commit may be refreshed.
      update plm.sesame_capture
         set read_commit_sha = coalesce(p_read_commit_sha, read_commit_sha)
       where id = v_existing.id;
      return v_existing.id;
    else
      raise exception
        'begin_sesame_capture: capture_key % is %; start a NEW capture rather than reusing it',
        p_capture_key, v_existing.status;
    end if;
  end if;

  insert into plm.sesame_capture (
    capture_key, source_repository, source_commit_sha, read_commit_sha,
    source_manifest_sha256, portal_base_url, portal_slug, source_captured_at,
    status, expected_counts, raw_summary, created_by
  ) values (
    p_capture_key, p_source_repository, p_source_commit_sha, p_read_commit_sha,
    p_source_manifest_sha256, p_portal_base_url, p_portal_slug, p_source_captured_at,
    'loading', p_expected_counts, p_raw_summary, p_created_by
  )
  returning id into v_id;

  return v_id;
end;
$$;

