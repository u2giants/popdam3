-- is the privilege that matters. Public loses it; only service_role holds it.
revoke all on function plm.begin_sesame_capture(
  text,text,text,text,text,text,timestamptz,jsonb,jsonb,text,text) from public;
revoke all on function plm.complete_sesame_capture(
  uuid,jsonb,integer,boolean,boolean,boolean,integer,jsonb) from public;
grant execute on function plm.begin_sesame_capture(
  text,text,text,text,text,text,timestamptz,jsonb,jsonb,text,text) to service_role;
grant execute on function plm.complete_sesame_capture(
  uuid,jsonb,integer,boolean,boolean,boolean,integer,jsonb) to service_role;

-- latest_sesame_capture() is a READ helper, not a write path. It exposes one uuid and no
-- licensed value, and both reading roles already hold SELECT on plm.sesame_capture, so
-- granting it to authenticated as well as service_role adds no access they do not have --
-- it only makes the correct way to ask the question available to them. anon holds
-- nothing here and keeps nothing.
revoke all on function plm.latest_sesame_capture() from public;
grant execute on function plm.latest_sesame_capture() to service_role;
grant execute on function plm.latest_sesame_capture() to authenticated;


-- Assert the OUTCOME inside the migration, so this file cannot fail silently the way the
-- NBCU landing did. If the revokes did not take, this raises and the migration fails.
--
-- The counts below are derived from the claimed table list, not typed as literals twice:
-- 19 tables, of which 18 are insertable snapshots and one is the capture root.
do $$
declare
  v_bad    integer;
  v_tables integer;
begin
  select count(*) into v_tables
    from information_schema.tables
   where table_schema = 'plm' and table_name like 'sesame\_%' and table_type = 'BASE TABLE';
  if v_tables <> 19 then
    raise exception 'sesame landing: expected 19 tables, found %', v_tables;
  end if;

  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name like 'sesame\_%'
     and grantee in ('service_role','authenticated')
     and privilege_type in ('UPDATE','DELETE','TRUNCATE');
  if v_bad <> 0 then
    raise exception
      'sesame landing: % write grant(s) survive on sesame tables; immutability is INERT',
      v_bad;
  end if;

  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name = 'sesame_capture'
     and grantee = 'service_role' and privilege_type = 'INSERT';
  if v_bad <> 0 then
    raise exception 'sesame landing: plm.sesame_capture is still directly insertable';
  end if;

  -- A revoke that overshot into SELECT or INSERT would break the loader, so prove it did
  -- not: every table readable, every table but the capture root insertable.
  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name like 'sesame\_%'
     and grantee = 'service_role' and privilege_type = 'SELECT';
  if v_bad <> v_tables then
    raise exception 'sesame landing: expected % service_role SELECT grants, found %',
      v_tables, v_bad;
  end if;

  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name like 'sesame\_%'
     and grantee = 'service_role' and privilege_type = 'INSERT';
  if v_bad <> v_tables - 1 then
    raise exception 'sesame landing: expected % service_role INSERT grants, found %',
      v_tables - 1, v_bad;
  end if;

  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name like 'sesame\_%'
     and grantee = 'authenticated' and privilege_type = 'SELECT';
  if v_bad <> v_tables then
    raise exception 'sesame landing: expected % authenticated SELECT grants, found %',
      v_tables, v_bad;
  end if;

  select count(*) into v_bad
    from information_schema.role_table_grants
   where table_schema = 'plm' and table_name like 'sesame\_%' and grantee = 'anon';
  if v_bad <> 0 then
    raise exception 'sesame landing: anon holds % grant(s) on sesame tables', v_bad;
  end if;

  -- The functions are the write path; assert their EXECUTE privilege too, or the
  -- immutability model has a hole nobody can see in the table grants. begin_ is the
  -- INSERT path to the capture root, so its lockdown matters at least as much as
  -- complete_'s; asserting only one would leave a leaked default EXECUTE on the other
  -- entirely invisible.
  if has_function_privilege('anon',
       'plm.complete_sesame_capture(uuid,jsonb,integer,boolean,boolean,boolean,integer,jsonb)',
       'EXECUTE')
     or has_function_privilege('authenticated',
       'plm.complete_sesame_capture(uuid,jsonb,integer,boolean,boolean,boolean,integer,jsonb)',
       'EXECUTE') then
    raise exception
      'sesame landing: complete_sesame_capture is executable outside service_role';
  end if;
  if not has_function_privilege('service_role',
       'plm.complete_sesame_capture(uuid,jsonb,integer,boolean,boolean,boolean,integer,jsonb)',
       'EXECUTE') then
    raise exception 'sesame landing: service_role cannot execute complete_sesame_capture';
  end if;
  if has_function_privilege('anon',
       'plm.begin_sesame_capture(text,text,text,text,text,text,timestamptz,jsonb,jsonb,text,text)',
       'EXECUTE')
     or has_function_privilege('authenticated',
       'plm.begin_sesame_capture(text,text,text,text,text,text,timestamptz,jsonb,jsonb,text,text)',
       'EXECUTE') then
    raise exception
      'sesame landing: begin_sesame_capture is executable outside service_role';
  end if;
  if not has_function_privilege('service_role',
       'plm.begin_sesame_capture(text,text,text,text,text,text,timestamptz,jsonb,jsonb,text,text)',
       'EXECUTE') then
    raise exception 'sesame landing: service_role cannot execute begin_sesame_capture';
  end if;
  if has_function_privilege('anon', 'plm.latest_sesame_capture()', 'EXECUTE') then
    raise exception 'sesame landing: latest_sesame_capture is executable by anon';
  end if;

  raise notice
    'sesame privileges: service_role SELECT x% / INSERT x%, no UPDATE/DELETE/TRUNCATE, anon none',
    v_tables, v_tables - 1;
end;
$$;


-- Assert the SHAPE guarantees that this landing is worthless without, so a later edit
-- that quietly drops one fails HERE rather than in a load six weeks from now.
do $$
declare
  v_n integer;
begin
  -- THE REFUSED RELATIONSHIP. No table in this schema may hold a brand-to-character link,
  -- derived or otherwise. The portal never states it, and pairing two independent fields
  -- on a shared asset is the Disney DCP Vault fabrication.
  select count(*) into v_n
    from information_schema.tables
   where table_schema = 'plm'
     and table_name like 'sesame\_%'
     and table_name like '%brand%'
     and table_name like '%character%';
  if v_n <> 0 then
    raise exception
      'sesame landing: % brand-to-character table(s) exist; that link is refused', v_n;
  end if;

  -- No media may ever be stored on the asset table, and no download path either.
  select count(*) into v_n
    from information_schema.columns
   where table_schema = 'plm' and table_name = 'sesame_asset'
     and (column_name in ('bytes','media','content','blob','base64','file_bytes',
                          'thumbnail','thumbnail_url','preview_url','download_path')
          or data_type = 'bytea');
  if v_n <> 0 then
    raise exception 'sesame landing: plm.sesame_asset carries % media-bearing column(s)',
      v_n;
  end if;

  -- THE DENORMALIZATION REFUSAL. Every one of these axes is multi-valued in the source,
  -- so a column here would be a lie on the thousands of assets carrying several. They
  -- live in the link tables and nowhere else.
  select count(*) into v_n
    from information_schema.columns
   where table_schema = 'plm' and table_name = 'sesame_asset'
     and (column_name like '%brand%' or column_name like '%character%'
          or column_name like '%style_guide%' or column_name like '%art_style%'
          or column_name like '%theme%' or column_name like '%asset_type%');
  if v_n <> 0 then
    raise exception
      'sesame landing: plm.sesame_asset carries % denormalized vocabulary column(s); those axes are multi-valued and belong only in the link tables',
      v_n;
  end if;

  -- THE DERIVED TABLE IS THE ONLY ONE. Exactly one table under this prefix may carry a
  -- relationship_truth column that is not pinned to 'declared'. If a second derived table
  -- ever appears without its own issue, this is what notices.
  select count(*) into v_n
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_namespace n on n.oid = t.relnamespace
   where n.nspname = 'plm' and t.relname like 'sesame\_%'
     and c.contype = 'c'
     and pg_get_constraintdef(c.oid) like '%relationship_truth = ''derived''%';
  if v_n <> 1 then
    raise exception
      'sesame landing: expected exactly 1 derived-relationship table, found %', v_n;
  end if;

  -- And every other relationship-bearing table must be pinned to 'declared'. Eight link
  -- tables carry the column: asset_category plus the seven asset-to-vocabulary tables.
  select count(*) into v_n
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_namespace n on n.oid = t.relnamespace
   where n.nspname = 'plm' and t.relname like 'sesame\_%'
     and c.contype = 'c'
     and pg_get_constraintdef(c.oid) like '%relationship_truth = ''declared''%';
  if v_n <> 8 then
    raise exception
      'sesame landing: expected 8 declared-relationship tables, found %', v_n;
  end if;

  -- source_md5 must stay NULLABLE: a handful of assets in this portal carry none, and a
  -- NOT NULL here would force the loader to invent one or drop the asset.
  select count(*) into v_n
    from information_schema.columns
   where table_schema = 'plm' and table_name = 'sesame_asset'
     and column_name = 'source_md5' and is_nullable = 'YES';
  if v_n <> 1 then
    raise exception 'sesame landing: plm.sesame_asset.source_md5 must exist and be NULLABLE';
  end if;

  -- field_generation must be part of the PRIMARY KEY on every vocabulary table. With it
  -- outside the key, the two generations collapse by case folding and a winner is picked
  -- silently -- which is the single worst thing this schema could do.
  select count(*) into v_n
    from pg_index i
    join pg_class t on t.oid = i.indrelid
    join pg_namespace n on n.oid = t.relnamespace
    join pg_attribute a on a.attrelid = t.oid and a.attnum = any(i.indkey)
   where n.nspname = 'plm'
     and t.relname in ('sesame_brand','sesame_sub_brand','sesame_character',
                       'sesame_style_guide','sesame_art_style','sesame_asset_type',
                       'sesame_theme')
     and i.indisprimary
     and a.attname = 'field_generation';
  if v_n <> 7 then
    raise exception
      'sesame landing: field_generation is in only % of 7 vocabulary primary keys', v_n;
  end if;

  -- in_licensee_portal must exist and be NOT NULL. The out-of-portal folders land, and an
  -- unflagged one would be read as licensing content.
  select count(*) into v_n
    from information_schema.columns
   where table_schema = 'plm' and table_name = 'sesame_category'
     and column_name = 'in_licensee_portal' and is_nullable = 'NO';
  if v_n <> 1 then
    raise exception
      'sesame landing: plm.sesame_category.in_licensee_portal must exist and be NOT NULL';
  end if;

  -- is_guide_level must NOT be a foreign key to plm.sesame_style_guide. The folder form
  -- and the field-value form of a style guide are different objects and only a minority
  -- of the values match; asserting the rest is an unmade human ruling.
  select count(*) into v_n
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_class r on r.oid = c.confrelid
    join pg_namespace n on n.oid = t.relnamespace
   where n.nspname = 'plm' and t.relname = 'sesame_category' and c.contype = 'f'
     and r.relname = 'sesame_style_guide';
  if v_n <> 0 then
    raise exception
      'sesame landing: plm.sesame_category has % foreign key(s) to plm.sesame_style_guide; the folder form and the field-value form are NOT the same object',
      v_n;
  end if;

  -- No reconciliation surface ships in this release. A half-built one is worse than none:
  -- it reads as "resolution exists and nothing resolved yet".
  select count(*) into v_n
    from information_schema.columns
   where table_schema = 'plm' and table_name like 'sesame\_%'
     and column_name in ('core_property_id','core_character_id','core_licensor_id',
                         'resolved_at','resolution_status');
  if v_n <> 0 then
    raise exception
      'sesame landing: % reconciliation column(s) shipped; this release resolves nothing',
      v_n;
  end if;

  raise notice
    'sesame shape: 19 tables, no brand-to-character link, no media, no denormalized axis, 1 derived table, 8 declared';
end;
$$;


