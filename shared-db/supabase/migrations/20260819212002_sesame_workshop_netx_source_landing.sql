language plpgsql
security definer
set search_path = plm, pg_temp
as $$
declare
  v_cap  plm.sesame_capture%rowtype;
  v_exp  jsonb;
  v_obs  jsonb := '{}'::jsonb;
  v_err  jsonb := '[]'::jsonb;
  v_n    bigint;
  v_d    bigint;
  v_want bigint;
  v_key  text;
  v_val  jsonb;
  v_max  numeric := 9223372036854775807::numeric;
  -- The eighteen snapshot tables. plm.sesame_capture itself is not counted: it is the
  -- root, not a member.
  v_pairs text[][] := array[
    ['categories',            'sesame_category'],
    ['brands',                'sesame_brand'],
    ['sub_brands',            'sesame_sub_brand'],
    ['characters',            'sesame_character'],
    ['style_guides',          'sesame_style_guide'],
    ['art_styles',            'sesame_art_style'],
    ['asset_types',           'sesame_asset_type'],
    ['themes',                'sesame_theme'],
    ['assets',                'sesame_asset'],
    ['asset_categories',      'sesame_asset_category'],
    ['asset_brands',          'sesame_asset_brand'],
    ['asset_sub_brands',      'sesame_asset_sub_brand'],
    ['asset_characters',      'sesame_asset_character'],
    ['asset_style_guides',    'sesame_asset_style_guide'],
    ['asset_art_styles',      'sesame_asset_art_style'],
    ['asset_asset_types',     'sesame_asset_asset_type'],
    ['asset_themes',          'sesame_asset_theme'],
    ['style_guide_characters','sesame_style_guide_character']
  ];
  i integer;
begin
  -- ARGUMENT VALIDATION HAPPENS AFTER THE ROW LOCK, DELIBERATELY, AND RECORDS ITS
  -- REFUSAL INSTEAD OF RAISING.
  --
  -- Raising here aborts before any 'rejected' row is written. A loader that passes SQL
  -- null, or the wrong jsonb in the wrong slot, then leaves the capture in 'loading' with
  -- NO recorded reason, and a retry with the same arguments dies identically: the capture
  -- is WEDGED. That is the same failure class as the raw cast in defect (2), arriving
  -- through a different door. The lock is taken FIRST so that there IS a row to record
  -- the refusal on.
  --
  -- Note the explicit `is null` test on each argument below. `jsonb_typeof(null)` is
  -- NULL, so `jsonb_typeof(x) <> 'object'` ALONE is UNKNOWN for a SQL NULL and the `if`
  -- would never fire -- the same never-false shape as defect (1), one level up.

  -- The row lock serialises two loaders completing the same capture.
  select * into v_cap from plm.sesame_capture where id = p_capture_id for update;
  if not found then
    -- No row exists, so there is nothing to record a refusal ON. Raising is the only
    -- honest option here and it cannot wedge anything.
    raise exception 'complete_sesame_capture: no capture %', p_capture_id;
  end if;
  if v_cap.status = 'complete' then
    -- Idempotent. A retry after a successful completion is a no-op, not an error.
    return;
  end if;
  if v_cap.status <> 'loading' then
    raise exception 'complete_sesame_capture: capture % is %, not loading',
      p_capture_id, v_cap.status;
  end if;

  -- Now that a row is locked, an unusable argument becomes recorded evidence rather than
  -- a wedge. Nothing below may run on a non-object p_observed_counts: `?` and `->`
  -- against a jsonb array or scalar answer about the wrong thing rather than failing.
  if p_observed_counts is null or jsonb_typeof(p_observed_counts) <> 'object' then
    v_err := v_err || jsonb_build_object(
      'code','observed_counts_not_an_object',
      'json_type', coalesce(jsonb_typeof(p_observed_counts), 'sql_null'));
  end if;
  if p_error_summary is null or jsonb_typeof(p_error_summary) <> 'array' then
    v_err := v_err || jsonb_build_object(
      'code','error_summary_not_an_array',
      'json_type', coalesce(jsonb_typeof(p_error_summary), 'sql_null'));
  end if;
  -- A NULL boolean flag is NOT false. `if not p_category_tree_walked` is UNKNOWN on a
  -- NULL and never fires -- defect (1) again, in boolean clothing. Name it instead.
  if p_category_tree_walked is null or p_pagination_verified is null
     or p_multivalue_parse_verified is null then
    v_err := v_err || jsonb_build_object('code','verification_flag_is_null');
  end if;
  if p_categories_visited is null then
    v_err := v_err || jsonb_build_object('code','categories_visited_is_null');
  elsif p_categories_visited < 0 then
    v_err := v_err || jsonb_build_object('code','categories_visited_negative',
                                         'supplied', p_categories_visited);
  end if;
  if p_guide_character_rows_excluded is null then
    v_err := v_err || jsonb_build_object('code','guide_character_rows_excluded_is_null');
  elsif p_guide_character_rows_excluded < 0 then
    v_err := v_err || jsonb_build_object('code','guide_character_rows_excluded_negative',
                                         'supplied', p_guide_character_rows_excluded);
  end if;
  if jsonb_array_length(v_err) > 0 then
    -- The bad arguments are exactly the ones we must not write, so the capture keeps its
    -- own defaults and only the refusal is recorded.
    update plm.sesame_capture
       set status            = 'rejected',
           load_completed_at = null,
           observed_counts   = '{}'::jsonb,
           error_summary     = v_err
     where id = p_capture_id;
    raise warning
      'complete_sesame_capture: capture % REJECTED on its arguments with % error(s): %',
      p_capture_id, jsonb_array_length(v_err), v_err;
    return;
  end if;

  v_exp := v_cap.expected_counts;

  -- ---- A. SCOPE AND COMPLETENESS.
  --
  -- THE NON-RECURSIVE-SEARCH GUARD. A crawler that queried only the top folders gets
  -- HTTP 200 and a size of zero from every one of them, so its capture looks entirely
  -- successful and is empty. The flag alone is only the loader's word for it; requiring
  -- categories_visited to equal the loaded category row count is the arithmetic behind
  -- the word. Both are needed: the flag catches "I did not walk it", the count catches
  -- "I walked some of it and set the flag anyway".
  if not p_category_tree_walked then
    v_err := v_err || jsonb_build_object('code','category_tree_not_walked');
  end if;
  if not p_pagination_verified then
    v_err := v_err || jsonb_build_object('code','pagination_not_verified');
  end if;
  if not p_multivalue_parse_verified then
    v_err := v_err || jsonb_build_object('code','multivalue_parse_not_verified');
  end if;

  select count(*) into v_n from plm.sesame_category where capture_id = p_capture_id;
  -- CAST BEFORE COMPARING. p_categories_visited is `integer` and v_n is `bigint`; the
  -- comparison is done in bigint so no value in the integer range can raise here. The
  -- argument was already refused by name above if it was null or negative.
  if v_n <> p_categories_visited::bigint then
    v_err := v_err || jsonb_build_object('code','categories_visited_disagrees_with_rows',
                                         'claimed', p_categories_visited, 'rows', v_n);
  end if;

  -- UNREACHABLE WHILE sesame_capture_media_zero_chk STANDS, AND KEPT ON PURPOSE.
  -- The column is `not null default 0` with a CHECK pinning it to zero, so no writer can
  -- put a nonzero value here today and no contract test can reach this branch without
  -- first dropping that constraint. It is defence in depth for the day someone does.
  -- Stated plainly rather than listed as tested, because a branch reported as covered
  -- when it is not is how the next reader is misled.
  if v_cap.media_downloaded <> 0 then
    v_err := v_err || jsonb_build_object('code','media_downloaded_nonzero',
                                         'observed', v_cap.media_downloaded);
  end if;

  -- ---- B. Errors the loader itself reported are fatal. A capture that knows it failed
  -- may never publish, whatever the counts say.
  if jsonb_array_length(p_error_summary) > 0 then
    v_err := v_err || jsonb_build_object('code','loader_reported_errors',
                                         'count', jsonb_array_length(p_error_summary));
  end if;

  -- ---- C. Counts, taken from the TABLES, never from a ledger or a summary document.
  -- Three facts must agree: what the source contract EXPECTED, what the loader CLAIMS it
  -- wrote, and what is ACTUALLY in the tables. Checking only two of the three lets a
  -- loader that miscounted its own output pass.
  --
  -- Read the long note above plm.begin_sesame_capture before editing any branch below.
  -- The branch order -- presence, then TYPE, then sign and integrality, then RANGE, and
  -- only then a cast -- is the whole defence, and it re-reads the STORED expected_counts
  -- rather than trusting that begin_ ever ran.
  for i in 1 .. array_length(v_pairs, 1) loop
    v_key := v_pairs[i][1];
    execute format('select count(*) from plm.%I where capture_id = $1', v_pairs[i][2])
      into v_n using p_capture_id;
    v_obs := v_obs || jsonb_build_object(v_key, v_n);

    if not (v_exp ? v_key) then
      v_err := v_err || jsonb_build_object('code','expected_count_missing','entity',v_key);
    elsif jsonb_typeof(v_exp -> v_key) <> 'number' then
      -- Catches BOTH the JSON null that would skip the check entirely and the
      -- numeric-looking string that would pass it on an untyped value.
      v_err := v_err || jsonb_build_object('code','expected_count_not_a_number',
                                           'entity',v_key,
                                           'json_type', jsonb_typeof(v_exp -> v_key));
    elsif (v_exp ->> v_key)::numeric < 0
       or (v_exp ->> v_key)::numeric <> trunc((v_exp ->> v_key)::numeric) then
      v_err := v_err || jsonb_build_object('code','expected_count_not_a_nonnegative_integer',
                                           'entity',v_key,'expected', v_exp -> v_key);
    elsif (v_exp ->> v_key)::numeric > v_max then
      v_err := v_err || jsonb_build_object('code','expected_count_out_of_range',
                                           'entity',v_key,'expected', v_exp -> v_key);
    else
      -- Through ::numeric, never straight to ::bigint: an integral JSON number written
      -- 1.0 renders as the text '1.0', which ::bigint refuses outright.
      v_want := ((v_exp ->> v_key)::numeric)::bigint;
      if v_n is distinct from v_want then
        v_err := v_err || jsonb_build_object('code','count_mismatch','entity',v_key,
                                             'expected',v_want,'observed',v_n);
      end if;
    end if;

    -- The loader's own reported counts carry the identical traps.
    if not (p_observed_counts ? v_key) then
      v_err := v_err || jsonb_build_object('code','reported_count_missing','entity',v_key);
    elsif jsonb_typeof(p_observed_counts -> v_key) <> 'number' then
      v_err := v_err || jsonb_build_object('code','reported_count_not_a_number',
                                           'entity',v_key,
                                           'json_type',
                                           jsonb_typeof(p_observed_counts -> v_key));
    elsif (p_observed_counts ->> v_key)::numeric < 0
       or (p_observed_counts ->> v_key)::numeric
           <> trunc((p_observed_counts ->> v_key)::numeric) then
      v_err := v_err || jsonb_build_object('code','reported_count_not_a_nonnegative_integer',
                                           'entity',v_key,
                                           'reported', p_observed_counts -> v_key);
    elsif (p_observed_counts ->> v_key)::numeric > v_max then
      v_err := v_err || jsonb_build_object('code','reported_count_out_of_range',
                                           'entity',v_key,
                                           'reported', p_observed_counts -> v_key);
    elsif ((p_observed_counts ->> v_key)::numeric)::bigint is distinct from v_n then
      v_err := v_err || jsonb_build_object('code','reported_count_mismatch','entity',v_key,
                                           'reported',
                                           ((p_observed_counts ->> v_key)::numeric)::bigint,
                                           'observed',v_n);
    end if;
  end loop;

  -- The loop above only inspects the eighteen entity keys this schema knows. A stored
  -- expected_counts or a reported observed_counts may carry OTHER keys -- media_downloaded
  -- is one, and a future loader may add more -- and an unusable value sitting in one of
  -- those is the same class of defect: a value that looks supplied and compares to
  -- nothing. Sweep the whole object so no key escapes the rule.
  --
  -- THE SWEEP APPLIES THE SAME THREE-PART RULE AS THE EIGHTEEN ENTITY KEYS -- type, then
  -- non-negative integer, then bigint range -- not a type test alone. A type-only sweep
  -- ignores -1 and 1.5 under an extra key while its comment claims every key is covered,
  -- and an owner UPDATE can plant exactly those. Neither shape can skip an entity count,
  -- so it is a truthfulness fix rather than a publication hole -- but a guard whose
  -- comment overstates it is how the next reader is misled.
  for v_key, v_val in select e.key, e.value from jsonb_each(v_exp) e
                       where not (v_obs ? e.key) loop
    if jsonb_typeof(v_val) <> 'number' then
      v_err := v_err || jsonb_build_object('code','expected_count_not_a_number',
                                           'entity',v_key,
                                           'json_type', jsonb_typeof(v_val));
    elsif (v_val #>> '{}')::numeric < 0
       or (v_val #>> '{}')::numeric <> trunc((v_val #>> '{}')::numeric) then
      v_err := v_err || jsonb_build_object('code','expected_count_not_a_nonnegative_integer',
                                           'entity',v_key,'expected', v_val);
    elsif (v_val #>> '{}')::numeric > v_max then
      v_err := v_err || jsonb_build_object('code','expected_count_out_of_range',
                                           'entity',v_key,'expected', v_val,'max', v_max);
    end if;
  end loop;
  for v_key, v_val in select e.key, e.value from jsonb_each(p_observed_counts) e
                       where not (v_obs ? e.key) loop
    if jsonb_typeof(v_val) <> 'number' then
      v_err := v_err || jsonb_build_object('code','reported_count_not_a_number',
                                           'entity',v_key,
                                           'json_type', jsonb_typeof(v_val));
    elsif (v_val #>> '{}')::numeric < 0
       or (v_val #>> '{}')::numeric <> trunc((v_val #>> '{}')::numeric) then
      v_err := v_err || jsonb_build_object('code','reported_count_not_a_nonnegative_integer',
                                           'entity',v_key,'reported', v_val);
    elsif (v_val #>> '{}')::numeric > v_max then
      v_err := v_err || jsonb_build_object('code','reported_count_out_of_range',
                                           'entity',v_key,'reported', v_val,'max', v_max);
    end if;
  end loop;

  -- ---- D. THE MULTI-VALUE PARSE EVIDENCE. p_multivalue_parse_verified is the loader's
  -- CLAIM; this is the evidence behind it. The source delivers a multi-valued field as
  -- ONE CSV-quoted string, so a loader that never splits produces a capture with exactly
  -- one value per asset per axis -- a perfectly plausible-looking, entirely wrong result
  -- that no row count reveals.
  --
  -- Checked on the CHARACTER and STYLE-GUIDE axes ONLY, and that restraint is deliberate.
  -- Those two are densely multi-valued in this source, so a capture with no multi-valued
  -- asset on either is a parse failure with near-certainty. The sparse axes -- sub-brand
  -- above all, which only a double-digit handful of assets carry at all -- may
  -- legitimately contain no multi-valued asset whatever, and demanding one there would
  -- reject a truthful capture. A guard that fires on good data gets disabled.
  if p_multivalue_parse_verified then
    select count(*) into v_n from plm.sesame_asset_character
     where capture_id = p_capture_id and field_generation = 'current';
    if v_n > 0 then
      select count(*) into v_d from (
        select 1 from plm.sesame_asset_character
         where capture_id = p_capture_id and field_generation = 'current'
         group by asset_source_id having count(*) > 1 limit 1) s;
      if v_d = 0 then
        v_err := v_err || jsonb_build_object(
          'code','multivalue_parse_shows_no_multivalued_asset',
          'entity','asset_character',
          'rows', v_n,
          'note','every asset carries exactly one value on a densely multi-valued axis, which is the signature of a CSV string passed through unparsed');
      end if;
    end if;

    select count(*) into v_n from plm.sesame_asset_style_guide
     where capture_id = p_capture_id and field_generation = 'current';
    if v_n > 0 then
      select count(*) into v_d from (
        select 1 from plm.sesame_asset_style_guide
         where capture_id = p_capture_id and field_generation = 'current'
         group by asset_source_id having count(*) > 1 limit 1) s;
      if v_d = 0 then
        v_err := v_err || jsonb_build_object(
          'code','multivalue_parse_shows_no_multivalued_asset',
          'entity','asset_style_guide',
          'rows', v_n,
          'note','every asset carries exactly one value on a densely multi-valued axis, which is the signature of a CSV string passed through unparsed');
      end if;
    end if;
  end if;

  -- ---- E. THE DERIVED/DECLARED SEPARATION, asserted rather than assumed. The CHECK
  -- constraints already pin these; this asserts that they are still in force rather than
  -- trusting that no later migration weakened one. It is cheap and it fails loudly.
  select count(*) into v_n from plm.sesame_style_guide_character
   where capture_id = p_capture_id and relationship_truth <> 'derived';
  if v_n <> 0 then
    v_err := v_err || jsonb_build_object('code','style_guide_character_not_derived',
                                         'rows',v_n);
  end if;
  select count(*) into v_n from plm.sesame_style_guide_character
   where capture_id = p_capture_id and derivation_method <> 'single_guide_asset';
  if v_n <> 0 then
    v_err := v_err || jsonb_build_object('code','style_guide_character_unknown_method',
                                         'rows',v_n);
  end if;
  select count(*) into v_n from plm.sesame_asset_category
   where capture_id = p_capture_id and relationship_truth <> 'declared';
  if v_n <> 0 then
    v_err := v_err || jsonb_build_object('code','asset_category_not_declared','rows',v_n);
  end if;
  select count(*) into v_n from plm.sesame_asset_character
   where capture_id = p_capture_id and relationship_truth <> 'declared';
  if v_n <> 0 then
    v_err := v_err || jsonb_build_object('code','asset_character_not_declared','rows',v_n);
  end if;

  -- ---- F. THE DERIVATION'S OWN HONESTY, MEASURED AGAINST THE EVIDENCE.
  --
  -- guide_character_rows_excluded is the count of character rows the derivation REFUSED
  -- to attribute, because their asset carried more than one style guide and could not be
  -- split. The evidence for that number is computable from the rows in front of us:
  -- v_d below is the number of current-generation CHARACTER APPEARANCES sitting on
  -- current-generation MULTI-GUIDE assets. That is exactly the population the derivation
  -- walks past.
  --
  -- THIS PREDICATE WAS WRONG IN THE FIRST DRAFT OF THIS FILE AND THE MISTAKE IS WORTH
  -- RECORDING, because it is the failure mode a guard is most likely to have. The first
  -- version tested only whether a multi-guide ASSET existed and never looked at
  -- characters at all. It therefore:
  --   * REFUSED A TRUTHFUL CAPTURE. Thousands of assets in this source carry no character
  --     whatsoever. A capture whose multi-guide assets are all character-free excludes
  --     NOTHING, so zero is the honest answer -- and the old predicate rejected it unless
  --     the loader invented a positive number. A guard that can only be satisfied by a
  --     fabrication is worse than no guard.
  --   * RUBBER-STAMPED A FAKE. Any nonzero value passed unexamined.
  -- Found in external review of PR #1274 (Grok 4.6, rotation 229) at commit 23cf4e9.
  --
  -- AND THE SECOND DRAFT WAS ALSO WRONG, IN A SUBTLER WAY WORTH RECORDING. It rejected a
  -- reported ZERO and rejected a report ABOVE the population, and accepted every integer
  -- in between. A capture with a thousand excludable character rows could therefore
  -- report ONE and publish: the audit column whose entire job is to make the skip list
  -- visible would understate it by three orders of magnitude, and the lie would be
  -- detectable only AFTER publication rather than prevented. Found in delta review of
  -- PR #1274 (Grok 4.6, rotation 231) at commit 8049953.
  --
  -- THE REASON GIVEN FOR STOPPING SHORT WAS REFUTED BY THIS FILE'S OWN TEST FIXTURE, and
  -- that is the part worth remembering. The claim was that a loader counting distinct
  -- (guide, character) PAIRS rather than appearance ROWS would produce a legitimately
  -- SMALLER number, so equality would reject honest captures. On the H-C fixture an
  -- unsplittable asset carries TWO guides and ONE character: the appearance count is 1
  -- and the pair count is 2. Pair-counting is smaller only where the same pairs repeat
  -- across many assets; here it is LARGER, and the upper bound already refused it -- so
  -- the test asserted that the pair count was an impossible fabrication while the comment
  -- called that same number a legitimate alternative. Both could not be true.
  --
  -- NOR IS THIS THE depth/parent SITUATION REFUSED ON plm.sesame_category. That was TWO
  -- VALID SHAPES THE SOURCE MIGHT HAVE, which we do not get to choose between. This is
  -- ONE SPECIFIED CENSUS OF OUR OWN SKIP LIST, computed by our own derivation from rows
  -- we already hold -- the same kind of fact as categories_visited equalling the category
  -- row count, and enforced the same way.
  --
  -- SO THE RULE IS EQUALITY: guide_character_rows_excluded MUST EQUAL v_d exactly. The
  -- three branches below are ONE RULE reported three ways, because the three mistakes
  -- have three different causes and an operator should be told which one was made:
  -- never counted, under-counted, or claimed more than exists.
  select count(*) into v_d
    from plm.sesame_asset_character ac
   where ac.capture_id = p_capture_id
     and ac.field_generation = 'current'
     and exists (
       select 1 from plm.sesame_asset_style_guide sg
        where sg.capture_id = ac.capture_id
          and sg.asset_source_id = ac.asset_source_id
          and sg.field_generation = 'current'
        group by sg.asset_source_id having count(*) > 1);
  -- Recorded on every capture, passing or failing: the number the loader's claim should
  -- be read against is worth as much as the claim.
  v_obs := v_obs || jsonb_build_object(
    'guide_character_rows_excludable', v_d,
    'guide_character_rows_excluded_reported', p_guide_character_rows_excluded);

  -- CAST BEFORE COMPARING. p_guide_character_rows_excluded is `integer` and v_d is
  -- `bigint`; every comparison below is done in bigint, so nothing in the integer range
  -- can raise here. The argument was already refused BY NAME above if it was null or
  -- negative, so only a non-negative in-range integer reaches this point.
  --
  -- NOTE WHAT IS DELIBERATELY *NOT* IN THIS CONDITION: a "derived rows exist" conjunct.
  -- The second draft carried one and it opened a hole of its own -- a capture whose
  -- derivation produced NO rows at all, sitting on a large excludable population, could
  -- report zero and publish, because the guard declined to look. Whether the derivation
  -- produced any output has nothing to do with whether its skip list was counted
  -- honestly.
  if p_guide_character_rows_excluded::bigint is distinct from v_d then
    if p_guide_character_rows_excluded = 0 then
      -- NEVER COUNTED. The headline case: a skip list exists and the capture reports none
      -- of it. This is the shape the column was added to prevent.
      v_err := v_err || jsonb_build_object(
        'code','guide_character_exclusions_not_counted',
        'excludable_character_rows', v_d,
        'note','character rows sit on assets carrying more than one style guide, so the derivation excluded them, but the capture reports zero exclusions');
    elsif p_guide_character_rows_excluded::bigint > v_d then
      -- IMPOSSIBLE. More excluded than exist to be excluded.
      v_err := v_err || jsonb_build_object(
        'code','guide_character_exclusions_exceed_evidence',
        'reported', p_guide_character_rows_excluded,
        'excludable_character_rows', v_d,
        'note','the capture claims it excluded more character rows than sit on multi-guide assets in this capture; no reading of the derivation rule can produce that number');
    else
      -- UNDER-COUNTED, and catchable only by equality. This branch is the reason equality
      -- is the rule: an audit column that may be reported as any number between one and
      -- the truth is not an audit column.
      v_err := v_err || jsonb_build_object(
        'code','guide_character_exclusions_understate_evidence',
        'reported', p_guide_character_rows_excluded,
        'excludable_character_rows', v_d,
        'note','the capture reports fewer excluded character rows than sit on multi-guide assets in this capture; this count is a census of the derivation own skip list and must be exact');
    end if;
  end if;

  -- ---- G. THE REFUSED RELATIONSHIP, checked in the running database and not only in the
  -- migration that created the schema. No brand-to-character table may exist under this
  -- prefix, derived or otherwise. A later migration could add one; this is what notices.
  select count(*) into v_n
    from information_schema.tables
   where table_schema = 'plm'
     and table_name like 'sesame\_%'
     and table_name like '%brand%'
     and table_name like '%character%';
  if v_n <> 0 then
    v_err := v_err || jsonb_build_object('code','brand_character_table_exists','tables',v_n);
  end if;

  -- ---- H. Duplicate source identifiers. The primary keys already make these impossible;
  -- this asserts that they are still in force rather than trusting that no later
  -- migration weakened one.
  select count(*), count(distinct asset_source_id) into v_n, v_d
    from plm.sesame_asset where capture_id = p_capture_id;
  if v_n <> v_d then
    v_err := v_err || jsonb_build_object('code','duplicate_asset_source_id',
                                         'rows',v_n,'distinct',v_d);
  end if;
  select count(*), count(distinct category_source_id) into v_n, v_d
    from plm.sesame_category where capture_id = p_capture_id;
  if v_n <> v_d then
    v_err := v_err || jsonb_build_object('code','duplicate_category_source_id',
                                         'rows',v_n,'distinct',v_d);
  end if;

  -- ---- I. VERDICT. There is no partial publish: either every check passed, or the
  -- capture is rejected and the PREVIOUS complete capture stays current.
  --
  -- WHY THIS DOES NOT `raise exception` ON A REJECTION, AND WHY THAT IS NOT A SILENT
  -- FAILURE. The contract requires BOTH "set status='rejected' and persist the errors"
  -- AND a loud failure. In PostgreSQL an exception aborts the very transaction that wrote
  -- the rejection row, so raising would roll back the evidence and leave the capture
  -- sitting in 'loading' with no record of why it failed -- destroying the auditability
  -- the rejection exists for. The same impossibility was recorded for
  -- plm.finalize_nbcu_capture (20260810070000), plm.finalize_sega_capture
  -- (20260819015333) and plm.finalize_peanuts_capture (20260819125713), and is resolved
  -- the same way here.
  -- The failure is loud in three simultaneous, inspectable ways:
  --   1. a WARNING in the server log,
  --   2. a PERSISTED status of 'rejected' with the structured errors,
  --   3. the capture is NOT 'complete', which is the only thing any reader keys on --
  --      plm.latest_sesame_capture() below can never return it.
  -- THE CALLER MUST READ BACK plm.sesame_capture.status. This function returns void by
  -- contract, so the status column is the return value.
  if jsonb_array_length(v_err) > 0 then
    update plm.sesame_capture
       set status                        = 'rejected',
           load_completed_at             = null,
           observed_counts               = v_obs,
           categories_visited            = p_categories_visited,
           category_tree_walked          = p_category_tree_walked,
           pagination_verified           = p_pagination_verified,
           multivalue_parse_verified     = p_multivalue_parse_verified,
           guide_character_rows_excluded = p_guide_character_rows_excluded,
           error_summary                 = v_err
     where id = p_capture_id;
    raise warning 'complete_sesame_capture: capture % REJECTED with % error(s): %',
      p_capture_id, jsonb_array_length(v_err), v_err;
    return;
  end if;

  update plm.sesame_capture
     set status                        = 'complete',
         load_completed_at             = now(),
         observed_counts               = v_obs,
         categories_visited            = p_categories_visited,
         category_tree_walked          = p_category_tree_walked,
         pagination_verified           = p_pagination_verified,
         multivalue_parse_verified     = p_multivalue_parse_verified,
         guide_character_rows_excluded = p_guide_character_rows_excluded,
         error_summary                 = '[]'::jsonb
   where id = p_capture_id;
end;
$$;

comment on function plm.complete_sesame_capture(
  uuid, jsonb, integer, boolean, boolean, boolean, integer, jsonb) is
  'Publishes or REJECTS one loading Sesame capture. Re-validates the STORED '
  'expected_counts rather than trusting begin_sesame_capture ran, because an owner UPDATE '
  'can reach that column without the function. Every count must be a JSON NUMBER that is '
  'a non-negative integer within bigint range -- a null, a numeric-looking string, a '
  'fraction or an oversized value is a NAMED error code, never a skipped check and never '
  'a raw cast error. Counts come from the TABLES, and expected, reported and actual must '
  'all three agree. categories_visited must equal the loaded category row count, and the '
  'multi-value parse claim is checked against the rows on the two densely multi-valued '
  'axes. All pass -> status ''complete''. Any fail -> status ''rejected'', errors '
  'PERSISTED, a server WARNING raised, and the previous complete capture left current. '
  'NEVER a partial publish, and NEVER a raise instead of a record -- a rejected capture '
  'is evidence. It returns void by contract, so THE CALLER MUST READ BACK '
  'plm.sesame_capture.status. Idempotent on an already-complete capture. service_role '
  'only. The last two arguments carry defaults so the schema contract''s six-argument '
  'call still works; they exist because guide_character_rows_excluded and error_summary '
  'have no other write path -- service_role holds no UPDATE on the capture table.';


-- =====================================================================================
-- plm.latest_sesame_capture() -- THE ONLY CORRECT WAY TO ASK "WHICH CAPTURE IS CURRENT".
--
-- Every consumer must read through this rather than picking a capture by date, because a
-- date picker cannot tell a COMPLETE capture from one that is still LOADING or was
-- REJECTED -- and a rejected capture is retained on purpose, so it is sitting right there
-- with a plausible timestamp waiting to be chosen. Filtering on status is the whole point
-- of the function; a caller that re-implements it will eventually forget.
--
-- Returns NULL when no complete capture exists. NULL means "unknown", never "zero rows",
-- and a consumer that joins on it correctly returns nothing rather than inventing an
-- empty answer.
-- =====================================================================================
create or replace function plm.latest_sesame_capture()
returns uuid
language sql
stable
security definer
set search_path = plm, pg_temp
as $$
  select id
    from plm.sesame_capture
   where status = 'complete'
   order by source_captured_at desc, load_completed_at desc, id desc
   limit 1;
$$;

comment on function plm.latest_sesame_capture() is
  'The id of the most recent COMPLETE Sesame capture, or NULL when none exists. Every '
  'consumer reads through this instead of picking a capture by date, so a rejected or '
  'in-flight load can never be read as current. NULL means unknown, never zero rows.';

