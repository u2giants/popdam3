-- =====================================================================================
-- 2-7. THE VOCABULARY TABLES -- the axes the portal issues NO IDENTIFIER for.
--
-- Six tables share one shape, and they share it because six axes in this portal are
-- LABEL-ONLY. In every one of them identity is `value_key`, a normalized label
-- (case-folded, whitespace-collapsed, quote-stripped) GENERATED BY US, and
-- `value_label` is the licensor's own spelling kept verbatim beside it.
--
-- THERE IS NO source_value_id COLUMN, ANYWHERE IN THIS FAMILY, ON PURPOSE. The portal
-- exposes numeric IDs for categories and assets only, and its own choice-list API returns
-- EMPTY for every one of these axes. A nullable, permanently NULL id column would read to
-- the next person as "the portal issues one and this capture failed to collect it", which
-- is the opposite of the truth. The absence is the fact.
--
-- field_generation IS INSIDE THE PRIMARY KEY, NOT BESIDE IT. The legacy and current
-- generations of the same axis hold values that CASE-FOLD ONTO EACH OTHER while meaning
-- different curation states. With the generation outside the key, loading both would
-- collapse them and silently pick a winner -- destroying exactly the evidence this
-- landing exists to preserve. Nothing in this schema may join the two generations
-- together; that mapping is a business ruling.
--
-- asset_count is > 0, not >= 0. Unlike the Peanuts (Tenovos) landing, these vocabularies
-- have no independent source: they are the distinct values observed ON THE ASSETS,
-- because the choice-list API returns nothing. A zero-usage value therefore cannot exist
-- here and a row claiming one is a loader defect, not an unused vocabulary entry.
-- =====================================================================================

