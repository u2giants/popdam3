  business_path text NOT NULL CHECK (business_path IN (
    'factory_ningbo_nyo','factory_ningbo_customer','factory_nyo',
    'china_warehouse_ningbo_nyo','china_warehouse_ningbo_customer',
    'nyo_factory','nyo_ningbo','ningbo_nyo','ningbo_customer'
  )),
  workflow_state text NOT NULL DEFAULT 'draft' CHECK (workflow_state IN (
    'draft','confirmed','packed','shipped','received','delivered_reported',
    'delivery_exception','cancelled'
  )),
  contract_version text NOT NULL DEFAULT 'sample-tracking-release-a-v1'
    CHECK (contract_version = 'sample-tracking-release-a-v1'),
  created_by_user text NOT NULL CHECK (btrim(created_by_user) <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sample_workflow_valid_flow_path CHECK (
    (workflow_type = 'nyo_purchased_factory_reference' AND business_path IN ('nyo_ningbo','nyo_factory')) OR
    (workflow_type = 'vendor_unsolicited_offer' AND business_path IN ('factory_ningbo_nyo','factory_nyo')) OR
    (workflow_type = 'nyo_factory_make_request' AND business_path IN ('factory_ningbo_nyo','factory_ningbo_customer')) OR
    (workflow_type = 'nyo_remote_china_inventory_request' AND business_path IN (
      'china_warehouse_ningbo_nyo','china_warehouse_ningbo_customer','ningbo_nyo','ningbo_customer'
