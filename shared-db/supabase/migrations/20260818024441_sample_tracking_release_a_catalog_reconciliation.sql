-- Owner-authorized Release A catalog reconciliation.
-- Runs only after 20260814130000 and 20260814193402. It repairs the exact
-- partial-preview state and is a verified no-op reconciliation on a fresh target.
BEGIN;

DO $$
DECLARE v_present integer;
BEGIN
  IF (SELECT count(*) FROM supabase_migrations.schema_migrations
      WHERE version IN ('20260814130000','20260814193402')) <> 2 THEN
    RAISE EXCEPTION 'Release A reconciliation requires both approved predecessor ledger versions exactly once';
  END IF;
  IF to_regclass('dflow.sample_carrier') IS NULL
     OR to_regclass('dflow.sample_shipment') IS NULL THEN
    RAISE EXCEPTION 'Release A reconciliation requires carrier and shipment foundations';
  END IF;
  SELECT count(*) INTO v_present
  FROM (VALUES ('dflow.sample_creation_batch'),('dflow.sample_workflow'),('dflow.sample_path_revision')) AS expected(name)
  WHERE to_regclass(expected.name) IS NOT NULL;
  IF v_present NOT IN (0,3) THEN
    RAISE EXCEPTION 'Release A reconciliation refused mixed workflow catalog state: % of 3 tables exist', v_present;
  END IF;
  IF (SELECT count(*) FROM dflow.sample_carrier WHERE is_active) <> 4
     OR (SELECT count(*) FROM dflow.sample_carrier
         WHERE is_active AND carrier_code IN ('ups','fedex','dhl','usps')) <> 4 THEN
    RAISE EXCEPTION 'Release A reconciliation requires exactly the four approved active carrier seeds';
  END IF;
END $$;

