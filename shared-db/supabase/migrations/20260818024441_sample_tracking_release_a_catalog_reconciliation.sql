CREATE TABLE IF NOT EXISTS dflow.sample_path_revision (
  sample_path_revision_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_workflow_id bigint NOT NULL REFERENCES dflow.sample_workflow(sample_workflow_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  revision integer NOT NULL CHECK (revision > 0),
  business_path text NOT NULL CHECK (business_path IN (
    'factory_ningbo_nyo','factory_ningbo_customer','factory_nyo',
    'china_warehouse_ningbo_nyo','china_warehouse_ningbo_customer',
    'nyo_factory','nyo_ningbo','ningbo_nyo','ningbo_customer'
  )),
  reason text NOT NULL CHECK (btrim(reason) <> ''),
  changed_by_user text NOT NULL CHECK (btrim(changed_by_user) <> ''),
  changed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (sample_workflow_id, revision)
);

CREATE OR REPLACE FUNCTION dflow.validate_sample_path_revision()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_workflow_type text;
  v_expected_revision integer;
BEGIN
  SELECT workflow_type INTO v_workflow_type
  FROM dflow.sample_workflow
  WHERE sample_workflow_id = NEW.sample_workflow_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Sample workflow % does not exist', NEW.sample_workflow_id USING ERRCODE = '23503';
  END IF;
  IF NOT (
    (v_workflow_type = 'nyo_purchased_factory_reference' AND NEW.business_path IN ('nyo_ningbo','nyo_factory')) OR
    (v_workflow_type = 'vendor_unsolicited_offer' AND NEW.business_path IN ('factory_ningbo_nyo','factory_nyo')) OR
    (v_workflow_type = 'nyo_factory_make_request' AND NEW.business_path IN ('factory_ningbo_nyo','factory_ningbo_customer')) OR
    (v_workflow_type = 'nyo_remote_china_inventory_request' AND NEW.business_path IN (
      'china_warehouse_ningbo_nyo','china_warehouse_ningbo_customer','ningbo_nyo','ningbo_customer'
    ))
  ) THEN
    RAISE EXCEPTION 'Path % is invalid for workflow type %', NEW.business_path, v_workflow_type
      USING ERRCODE = '23514';
  END IF;
  SELECT COALESCE(max(revision),0) + 1 INTO v_expected_revision
  FROM dflow.sample_path_revision WHERE sample_workflow_id = NEW.sample_workflow_id;
  IF NEW.revision <> v_expected_revision THEN
    RAISE EXCEPTION 'Path revision must be %, received %', v_expected_revision, NEW.revision
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS sample_path_revision_validate ON dflow.sample_path_revision;
CREATE TRIGGER sample_path_revision_validate
BEFORE INSERT ON dflow.sample_path_revision
FOR EACH ROW EXECUTE FUNCTION dflow.validate_sample_path_revision();

CREATE OR REPLACE FUNCTION dflow.require_sample_path_revision()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.business_path IS DISTINCT FROM OLD.business_path AND NOT EXISTS (
    SELECT 1 FROM dflow.sample_path_revision r
    WHERE r.sample_workflow_id = NEW.sample_workflow_id
      AND r.business_path = NEW.business_path
      AND r.revision = (SELECT max(r2.revision) FROM dflow.sample_path_revision r2
                        WHERE r2.sample_workflow_id = NEW.sample_workflow_id)
  ) THEN
    RAISE EXCEPTION 'Insert the append-only path revision before changing the workflow path'
      USING ERRCODE = '55000';
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS sample_workflow_path_revision_required ON dflow.sample_workflow;
CREATE TRIGGER sample_workflow_path_revision_required
BEFORE UPDATE OF business_path ON dflow.sample_workflow
FOR EACH ROW EXECUTE FUNCTION dflow.require_sample_path_revision();

CREATE OR REPLACE FUNCTION dflow.apply_sample_path_revision()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE dflow.sample_workflow
  SET business_path = NEW.business_path, updated_at = NEW.changed_at
  WHERE sample_workflow_id = NEW.sample_workflow_id;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS sample_path_revision_apply ON dflow.sample_path_revision;
CREATE TRIGGER sample_path_revision_apply
AFTER INSERT ON dflow.sample_path_revision
FOR EACH ROW EXECUTE FUNCTION dflow.apply_sample_path_revision();

CREATE OR REPLACE FUNCTION dflow.reject_sample_path_revision_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Sample path revisions are append-only' USING ERRCODE = '55000';
END $$;

DROP TRIGGER IF EXISTS sample_path_revision_immutable ON dflow.sample_path_revision;
CREATE TRIGGER sample_path_revision_immutable
BEFORE UPDATE OR DELETE ON dflow.sample_path_revision
FOR EACH ROW EXECUTE FUNCTION dflow.reject_sample_path_revision_mutation();

CREATE OR REPLACE FUNCTION dflow.validate_sample_shipment_line_header()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_header dflow.sample_shipment;
BEGIN
  IF NEW.sample_shipment_id IS NULL THEN RETURN NEW; END IF;
  SELECT * INTO v_header FROM dflow.sample_shipment WHERE sample_shipment_id=NEW.sample_shipment_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Shipment header % does not exist',NEW.sample_shipment_id USING ERRCODE='23503';
  END IF;
  IF NEW.origin_location_type IS DISTINCT FROM v_header.origin_location_type
     OR NEW.origin_location_id IS DISTINCT FROM v_header.origin_location_id
     OR NEW.destination_location_type IS DISTINCT FROM v_header.destination_location_type
     OR NEW.destination_location_id IS DISTINCT FROM v_header.destination_location_id THEN
    RAISE EXCEPTION 'Shipment line route must match shipment header %',NEW.sample_shipment_id
      USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS sample_shipment_line_header_route ON dflow.sample_shipment_line;
CREATE TRIGGER sample_shipment_line_header_route
BEFORE INSERT OR UPDATE OF sample_shipment_id,origin_location_type,origin_location_id,
  destination_location_type,destination_location_id ON dflow.sample_shipment_line
FOR EACH ROW EXECUTE FUNCTION dflow.validate_sample_shipment_line_header();
CREATE OR REPLACE VIEW dflow.sample_inventory AS
SELECT
  b.sample_id_fk,
  b.location_type,
  CASE
    WHEN b.location_type = 'terminal' AND b.location_id = 'nyc_office_inventory' THEN 'office'
    WHEN b.location_type = 'terminal' AND b.location_id = 'ningbo_office_inventory' THEN 'office'
    ELSE b.location_type
  END AS product_location_type,
  CASE
    WHEN b.location_id = 'nyc_office_inventory' THEN 'nyc'
    WHEN b.location_id = 'ningbo_office_inventory' THEN 'ningbo'
    ELSE b.location_id
  END AS product_location_id,
  b.quantity,
  max(m.occurred_at) AS available_since,
  EXISTS (
    SELECT 1 FROM dflow.sample_shipment_item si
    WHERE si.sample_id_fk = b.sample_id_fk AND si.box_id_fk IS NOT NULL
  ) AS is_boxed,
  (b.location_type = 'in_transit') AS is_in_transit,
  (b.quantity > 0 AND b.location_type <> 'in_transit') AS is_eligible,
  CASE WHEN b.quantity <= 0 THEN 'no_balance'
       WHEN b.location_type = 'in_transit' THEN 'in_transit'
       ELSE NULL END AS ineligibility_reason
FROM dflow.sample_balance_by_location b
LEFT JOIN dflow.sample_movement m
  ON m.sample_id_fk = b.sample_id_fk
 AND ((m.to_location_type = b.location_type AND m.to_location_id = b.location_id)
   OR (m.from_location_type = b.location_type AND m.from_location_id = b.location_id))
WHERE b.quantity > 0
GROUP BY b.sample_id_fk,b.location_type,b.location_id,b.quantity;

CREATE INDEX IF NOT EXISTS sample_movement_inventory_idx
  ON dflow.sample_movement (to_location_type, to_location_id, occurred_at DESC, sample_id_fk);

