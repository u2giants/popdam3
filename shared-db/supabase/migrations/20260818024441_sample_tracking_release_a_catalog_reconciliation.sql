  creation_batch_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mode text NOT NULL CHECK (mode IN ('single','group')),
  entry_method text NOT NULL CHECK (entry_method IN ('manual','inventory_selection','import_confirm')),
  idempotency_key text NOT NULL CHECK (btrim(idempotency_key) <> ''),
  request_hash text NOT NULL CHECK (btrim(request_hash) <> ''),
  created_by_user text NOT NULL CHECK (btrim(created_by_user) <> ''),
  created_by_role text NOT NULL CHECK (btrim(created_by_role) <> ''),
