#!/usr/bin/env node
// Emit the ColdLion licensor/property ROLLBACK SQL, bound to the frozen approved set.
//
// WHY THIS EXISTS
// ---------------
// The Step 7 rollback originally said:
//
//     delete from core.taxonomy_source_ref
//      where source_system = 'coldlion' and source_table = 'merchGroupDetails';
//
// which removes EVERY ColdLion taxonomy row, not the approved fingerprinted set — so a
// future ColdLion lane's rows would be collateral damage. The corrected version used
// a `:approved_mapping_json` placeholder that nothing binds, so it would not run at
// all (Grok review, 2026-07-28). Both are the same underlying fault: rollback SQL
// that was never executed by anyone.
//
// This generates the statement from the frozen approval artifact itself, so the
// rollback can only ever withdraw exactly what was approved. It writes SQL to stdout
// and touches no database — read it before you run it.
//
// Usage:
//   node tools/emit-coldlion-rollback-sql.mjs > rollback-approved.sql
//   # review it, then:
//   supabase db query --linked --file rollback-542.sql

import { pathToFileURL } from "node:url";
import { compositeKeyOf } from "./run-coldlion-licensor-property-phase4.mjs";
import {
  APPROVED_COUNT,
  loadWidenedApprovedMapping,
} from "./coldlion-paramount-five-approved-mapping.mjs";

export function buildRollbackSql(mappings) {
  if (!Array.isArray(mappings) || mappings.length !== APPROVED_COUNT) {
    throw new Error(
      `refusing to emit rollback SQL for ${mappings?.length ?? "unknown"} mappings; expected exactly ${APPROVED_COUNT}`,
    );
  }
  const keys = mappings.map(compositeKeyOf);
  for (const k of keys) {
    // Defensive: these come from a frozen, hash-pinned artifact, but this SQL is
    // executed against production, so refuse anything that could break out of a
    // string literal rather than escaping it and hoping.
    if (!/^[A-Za-z0-9._/-]+$/.test(k)) {
      throw new Error(`refusing unsafe composite source key: ${JSON.stringify(k)}`);
    }
  }
  const values = keys.map((k) => `    ('${k}')`).join(",\n");
  const paramountIds = [...new Set(mappings
    .filter((m) => ["AM1", "AM2", "MGM", "WND", "EP"].includes(m.mg_code))
    .map((m) => m.canonical_id))];
  if (paramountIds.length !== 5 || paramountIds.some((id) => !/^[0-9a-f-]{36}$/.test(id))) {
    throw new Error("refusing rollback: widened artifact does not identify exactly five safe canonical UUIDs");
  }
  const paramountValues = paramountIds.map((id) => `    ('${id}'::uuid)`).join(",\n");

  return `-- ColdLion licensor/property rollback — withdraws EXACTLY the approved ${APPROVED_COUNT} links.
-- Generated by tools/emit-coldlion-rollback-sql.mjs from the frozen approval artifact
-- docs/verification/coldlion-licensor-property-paramount-five-20260825/approved-mapping.json
--
-- Preserves every canonical identity and parent. The five #1177-created Properties
-- are set inactive after their exact links are withdrawn, so rollback does not
-- strand active, source-less Master Data rows.
-- The circuit breaker's delete guard refuses this while tripped, so reset under
-- authorization first, then RE-ARM immediately afterwards.

begin;

create temp table approved_rollback (source_id text primary key) on commit drop;

insert into approved_rollback (source_id) values
${values};

create temp table paramount_five_rollback (property_id uuid primary key) on commit drop;
insert into paramount_five_rollback(property_id) values
${paramountValues};

create temp table issue_1177_rollback_pre_snapshot(snapshot jsonb not null) on commit drop;
insert into issue_1177_rollback_pre_snapshot values(plm.compute_taxonomy_immutability_snapshot());

create temp table issue_1177_rollback_locked_pins(
  id uuid primary key, metric_key text not null, metric_kind text not null,
  expected_int integer, expected_text text
) on commit drop;
insert into issue_1177_rollback_locked_pins(id,metric_key,metric_kind,expected_int,expected_text)
select id,metric_key,metric_kind,expected_int,expected_text
from plm.taxonomy_baseline_pin
where baseline_key='phase4_preview' and superseded_at is null
  and metric_key in('property_count','taxonomy_source_ref_count','coldlion_source_ref_count',
    'linked_licensor_count','linked_property_count','property_uuid_hash','property_status_hash','parent_edge_hash')
for update;

-- Sanity: must be exactly ${APPROVED_COUNT}.
do $$
declare v_n integer;
begin
  select count(*) into v_n from approved_rollback;
  if v_n <> ${APPROVED_COUNT} then
    raise exception 'rollback set is % rows, expected ${APPROVED_COUNT}', v_n;
  end if;
end;
$$;

delete from core.taxonomy_source_ref r
 using approved_rollback a
 where r.source_system = 'coldlion'
   and r.source_table  = 'merchGroupDetails'
   and r.source_id     = a.source_id;

-- The mirror tables enforce link/status consistency:
--   plm_erp_licensor_resolution_link_ck / plm_erp_property_resolution_link_ck
--   require (auto_matched|manually_matched) => link IS NOT NULL, and
--           (unresolved|new_candidate|ambiguous|quarantined|ignored) => link IS NULL.
-- So the link and the resolution_status MUST be cleared together. Nulling the link
-- alone raises 23514 and aborts the whole rollback. Found on 2026-07-28 only by
-- actually running this SQL against preview inside a rolled-back transaction —
-- it would otherwise have failed mid-incident, at the worst possible moment.
update plm.erp_licensor e
   set licensor_id = null,
       resolution_status = 'unresolved'
 where e.licensor_id is not null
   and concat_ws('/', e.company_code, e.division_code, e.mg_type_code, e.mg_code)
       in (select source_id from approved_rollback);

update plm.erp_property e
   set property_id = null,
       resolution_status = 'unresolved'
 where e.property_id is not null
   and concat_ws('/', e.company_code, e.division_code, e.mg_type_code, e.mg_code)
       in (select source_id from approved_rollback);

-- The licensing write guard consumes one transaction-bound authorization per
-- canonical status change. Refuse unless all five rows are exactly the identities
-- created by #1177 and no approved ColdLion ref remains.
do $$
declare r record; v_n integer; v_plan uuid;
begin
  select count(*) into v_n
  from core.property p join paramount_five_rollback x on x.property_id=p.id
  where p.status='active'
    and p.metadata->>'implementation_issue'='#1177'
    and p.metadata->>'approval_issue'='#539'
    and p.metadata->>'approved_mapping_hash'='09e18e47d67181b06483d6cf4454e053'
    and not exists(select 1 from core.taxonomy_source_ref sr
      where sr.entity_table='property' and sr.entity_id=p.id
        and sr.source_system='coldlion' and sr.source_table='merchGroupDetails');
  if v_n<>5 then
    raise exception 'rollback found % of 5 exact active #1177 Properties safe to inactivate',v_n;
  end if;
  for r in select p.id from core.property p join paramount_five_rollback x on x.property_id=p.id
  loop
    v_plan:=gen_random_uuid();
    insert into plm.licensing_write_authorization(backend_pid,transaction_id,target_table,
      write_kind,plan_id,plan_hash,actor,protected_columns,expires_at)
    values(pg_backend_pid(),txid_current(),'core.property','coldlion_status',v_plan,
      encode(extensions.digest('1177/rollback/inactivate/'||r.id::text,'sha256'),'hex'),
      'generated #1177 rollback',array['status'],clock_timestamp()+interval '1 minute');
    update core.property set status='inactive' where id=r.id and status='active';
    get diagnostics v_n=row_count;
    if v_n<>1 then raise exception 'rollback inactivated % rows for Property %, expected 1',v_n,r.id; end if;
  end loop;
end;
$$;

-- Rollback changes environment-specific link/ref counts and Property status.
-- Supersede the exact eight affected locked pins, then pin the truthful live
-- snapshot so the health detector does not misclassify the authorized rollback
-- as unexplained drift and trip the shared breaker.
do $$
declare v_n integer; v_snap jsonb; v_pre jsonb;
begin
  select count(*) into v_n from issue_1177_rollback_locked_pins;
  if v_n<>8 then raise exception 'rollback found % of 8 required live affected baseline pins',v_n; end if;
  select snapshot into strict v_pre from issue_1177_rollback_pre_snapshot;
  v_snap:=plm.compute_taxonomy_immutability_snapshot();
  if v_snap->>'property_count' is distinct from v_pre->>'property_count'
     or (v_snap->>'taxonomy_source_ref_count')::integer>(v_pre->>'taxonomy_source_ref_count')::integer
     or (v_snap->>'coldlion_source_ref_count')::integer>(v_pre->>'coldlion_source_ref_count')::integer
     or (v_snap->>'linked_property_count')::integer>(v_pre->>'linked_property_count')::integer
     or (v_snap->>'linked_licensor_count')::integer>(v_pre->>'linked_licensor_count')::integer
     or ((v_pre->>'taxonomy_source_ref_count')::integer-(v_snap->>'taxonomy_source_ref_count')::integer)
        <>((v_pre->>'coldlion_source_ref_count')::integer-(v_snap->>'coldlion_source_ref_count')::integer)
     or ((v_pre->>'linked_property_count')::integer-(v_snap->>'linked_property_count')::integer)
       +((v_pre->>'linked_licensor_count')::integer-(v_snap->>'linked_licensor_count')::integer)
        <>((v_pre->>'coldlion_source_ref_count')::integer-(v_snap->>'coldlion_source_ref_count')::integer)
     or v_snap->>'licensor_count' is distinct from v_pre->>'licensor_count'
     or v_snap->>'designflow_source_ref_count' is distinct from v_pre->>'designflow_source_ref_count'
     or v_snap->>'licensor_uuid_hash' is distinct from v_pre->>'licensor_uuid_hash'
     or v_snap->>'licensor_status_hash' is distinct from v_pre->>'licensor_status_hash'
     or v_snap->>'property_uuid_hash' is distinct from v_pre->>'property_uuid_hash'
     or v_snap->>'parent_edge_hash' is distinct from v_pre->>'parent_edge_hash' then
    raise exception 'post-rollback snapshot is not the exact authorized ref/link withdrawal with identities and unrelated metrics stable; pre %, post %',v_pre,v_snap;
  end if;
  update plm.taxonomy_baseline_pin p set superseded_at=clock_timestamp()
  from issue_1177_rollback_locked_pins locked
  where p.id=locked.id and p.superseded_at is null
    and p.metric_key=locked.metric_key and p.metric_kind=locked.metric_kind
    and p.expected_int is not distinct from locked.expected_int
    and p.expected_text is not distinct from locked.expected_text;
  get diagnostics v_n=row_count;
  if v_n<>8 then raise exception 'rollback superseded % affected pins, expected 8',v_n; end if;
  insert into plm.taxonomy_baseline_pin(baseline_key,metric_key,metric_kind,expected_int,
    expected_text,effective_from,pinned_by,pinned_reason,source_migration)
  select 'phase4_preview',x.metric_key,x.metric_kind,x.expected_int,x.expected_text,
    clock_timestamp(),'Albert Hazan (owner)',
    'AUTHORIZED #1177 rollback: five canonical identities retained inactive; approved links withdrawn; exact post-rollback snapshot.',
    'rollback_20260825050407_coldlion_paramount_five_approved_gate'
  from (values
    ('property_count','count',(v_snap->>'property_count')::integer,null::text),
    ('taxonomy_source_ref_count','count',(v_snap->>'taxonomy_source_ref_count')::integer,null),
    ('coldlion_source_ref_count','count',(v_snap->>'coldlion_source_ref_count')::integer,null),
    ('linked_licensor_count','count',(v_snap->>'linked_licensor_count')::integer,null),
    ('linked_property_count','count',(v_snap->>'linked_property_count')::integer,null),
    ('property_uuid_hash','hash',null,v_snap->>'property_uuid_hash'),
    ('property_status_hash','hash',null,v_snap->>'property_status_hash'),
    ('parent_edge_hash','hash',null,v_snap->>'parent_edge_hash')
  ) x(metric_key,metric_kind,expected_int,expected_text);
end;
$$;

do $$
declare v_def text;
begin
  select pg_get_functiondef('plm.promote_coldlion_source_owned(jsonb,jsonb,boolean)'::regprocedure)
    into v_def;
  if v_def not like '%09e18e47d67181b06483d6cf4454e053%'
     or v_def not like '%''552''%' or v_def not like '%''276''%' then
    raise exception 'rollback refused: promotion function does not carry exact #1177 fingerprint';
  end if;
  v_def:=replace(v_def,'09e18e47d67181b06483d6cf4454e053','1230f5a12d0f2a3029f1d3df17fc5b5f');
  v_def:=replace(v_def,'''552''','''542''');
  v_def:=replace(v_def,'''276''','''271''');
  execute v_def;
  revoke all on function plm.promote_coldlion_source_owned(jsonb,jsonb,boolean)
    from public,anon,authenticated,service_role;
end;
$$;

-- Report what was withdrawn, so the operator sees it before committing.
select
  (select count(*) from core.taxonomy_source_ref
    where source_system = 'coldlion' and source_table = 'merchGroupDetails') as coldlion_refs_remaining,
  (select count(*) from plm.erp_licensor where licensor_id is not null) as mirror_licensor_links_remaining,
  (select count(*) from plm.erp_property where property_id is not null) as mirror_property_links_remaining;

commit;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { input } = loadWidenedApprovedMapping();
    process.stdout.write(buildRollbackSql(input.mappings));
  } catch (err) {
    process.stderr.write(`emit-coldlion-rollback-sql failed: ${err?.stack ?? err}\n`);
    process.exitCode = 1;
  }
}
