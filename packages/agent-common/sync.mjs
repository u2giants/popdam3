#!/usr/bin/env node
// Copies the shared agent sources (non-test .ts files in ./src) into the
// calling agent's src/common/ directory so each agent's own `tsc` compiles
// them into its existing dist/ output (ESM for bridge-agent, CommonJS for
// windows-agent). No runtime package is added and packaging is unchanged.
// The copies are generated and gitignored: edit packages/agent-common/src.
// Run from the agent directory (npm pre-scripts do this).
import { cpSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const srcDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "src");
const destDir = path.resolve(process.cwd(), process.argv[2] ?? "src/common");

rmSync(destDir, { recursive: true, force: true });
mkdirSync(destDir, { recursive: true });
const files = readdirSync(srcDir).filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"));
for (const f of files) cpSync(path.join(srcDir, f), path.join(destDir, f));
writeFileSync(
  path.join(destDir, "README.txt"),
  "GENERATED by packages/agent-common/sync.mjs - do not edit; edit packages/agent-common/src.\n",
);
console.log(`agent-common: synced ${files.length} file(s) into ${destDir}`);
